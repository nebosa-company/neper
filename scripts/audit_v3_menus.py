"""Prints the menu tree of MTG Studio v3's main form (menus, submenus and their item names) as markdown.

Usage: python scripts/audit_v3_menus.py > docs/grid-parity/v3-menu-tree.md
Item names are the Delphi component names (bbViewGroupByType ...); captions are looked up where the dfm has them.
"""
import re

PATH = r'D:\repos\mtg.studio.src\version-3\src\mtgstudio\ui\vcl\main.vcl.form.dfm'
text = open(PATH, encoding='utf-8', errors='replace').read().replace('\r', '')
actions = {}
for m in re.finditer(r"\n    object (\w+): TAction\n(.*?)\n    end(?=\n)", text, re.S):
    c = re.search(r"Caption = '([^']*)'", m.group(2))
    if c:
        actions[m.group(1)] = c.group(1)
caption = {}
for m in re.finditer(r"\n    object (\w+): (TdxBar\w+)\n(.*?)\n    end(?=\n)", text, re.S):
    body = '\n' + m.group(3)
    c = re.search(r"\n      Caption = '([^']*)'", body)
    a = re.search(r"\n      Action = (\w+)", body)
    shortcut = re.search(r"\n      ShortCut = (\d+)", body)
    label = c.group(1) if c else (actions.get(a.group(1)) if a else None)
    caption[m.group(1)] = (label, a.group(1) if a else None)
subs = {}
order = []
for m in re.finditer(r"\n    object (\w+): TdxBarSubItem\n(.*?)\n    end(?=\n)", text, re.S):
    items = re.findall(r"ItemName = '(\w+)'", m.group(2))
    if items:
        subs[m.group(1)] = items
        order.append(m.group(1))


def show(name, depth, out):
    label = caption.get(name, (None, None))[0] or ''
    out.append('%s- %s%s' % ('  ' * depth, name, (' - ' + label.replace('&', '')) if label else ''))
    if name in subs and depth < 4:
        for child in subs[name]:
            show(child, depth + 1, out)


out = ['# MTG Studio v3 menu tree', '',
       'Generated by `scripts/audit_v3_menus.py` from `main.vcl.form.dfm`. Names are the Delphi components; the caption follows when the form has one.', '']
tops = ['miDeck', 'miCards', 'miSearch', 'miView', 'bsiCardArt', 'bsiOnline', 'miReports', 'miTools', 'bsiAdmin', 'miHelp']
for top in tops:
    if top in subs:
        label = caption.get(top, (None, None))[0] or top
        out.append('## %s' % label.replace('&', ''))
        out.append('')
        for item in subs[top]:
            show(item, 0, out)
        out.append('')
print('\n'.join(out))
