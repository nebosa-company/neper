"""Lists every TcxGrid in MTG Studio v3's forms: its views, columns and read-only settings.

Usage: python scripts/audit_tcxgrid.py [dfm-root] > docs/grid-parity/tcxgrid-audit.md
Parses the Delphi .dfm text (object ... end nesting, Name = Value properties) and prints one section per grid.
"""
import os
import re
import sys

ROOT = sys.argv[1] if len(sys.argv) > 1 else r'D:\repos\mtg.studio.src\version-3\src'

VIEW_KEYS = [
    'OptionsData.Editing', 'OptionsData.Deleting', 'OptionsData.Inserting', 'OptionsData.Appending',
    'OptionsSelection.CellSelect', 'OptionsSelection.MultiSelect', 'OptionsSelection.InvertSelect',
    'OptionsSelection.HideFocusRectOnExit', 'OptionsSelection.HideSelection',
    'OptionsView.ColumnAutoWidth', 'OptionsView.GroupByBox', 'OptionsView.Footer', 'OptionsView.Indicator',
    'OptionsView.Header', 'OptionsView.CellAutoHeight', 'OptionsView.GridLines', 'OptionsView.NoDataToDisplayInfoText',
    'OptionsView.HeaderAutoHeight', 'OptionsView.FooterAutoHeight', 'OptionsView.ShowEditButtons',
    'OptionsView.CellEndEllipsis', 'OptionsView.BandHeaders', 'OptionsCustomize.ColumnMoving',
    'OptionsCustomize.ColumnSorting', 'OptionsCustomize.ColumnHiding', 'OptionsCustomize.ColumnGrouping',
    'OptionsCustomize.ColumnsQuickCustomization', 'FilterRow.Visible', 'Filtering.ColumnPopup.MaxDropDownItemCount',
    'Styles.StyleSheet', 'Styles.OnGetContentStyle', 'Styles.Content', 'Styles.ContentEven', 'Styles.ContentOdd',
    'DataController.DataSource', 'DataController.Summary.FooterSummaryItems',
]
COL_KEYS = [
    'Caption', 'Width', 'Visible', 'Options.Editing', 'Options.Focusing', 'Options.Sorting', 'Options.Moving',
    'Options.Grouping', 'Options.Filtering', 'Options.HorzSizing', 'Properties.ReadOnly', 'PropertiesClassName',
    'DataBinding.FieldName', 'SortOrder', 'SortIndex', 'GroupIndex', 'HeaderAlignmentHorz', 'Summary.FooterKind',
    'Styles.Content', 'Styles.Header', 'DataBinding.ValueType', 'MinWidth', 'RepositoryItem',
]


def parse(path):
    text = open(path, encoding='utf-8', errors='replace').read()
    root = {'kind': 'root', 'name': '', 'props': {}, 'kids': []}
    stack = [root]
    lines = text.split('\n')
    i = 0
    multi = 0
    opener = '<'
    closer = '>'
    while i < len(lines):
        raw = lines[i].rstrip('\r')
        s = raw.strip()
        i += 1
        if multi > 0:
            bare = re.sub(r"'(?:[^']|'')*'", '', s)
            multi += bare.count(opener) - bare.count(closer)
            if multi < 0:
                multi = 0
            continue
        m = re.match(r'(object|inherited|inline)\s+(\w+)\s*:\s*(\w+)', s)
        if m:
            node = {'kind': m.group(3), 'name': m.group(2), 'props': {}, 'kids': [], 'line': i}
            stack[-1]['kids'].append(node)
            stack.append(node)
            continue
        if s == 'end':
            if len(stack) > 1:
                stack.pop()
            continue
        m = re.match(r'([\w.]+)\s*=\s*(.*)', s)
        if m and len(stack) > 1:
            value = m.group(2)
            if value.endswith('<') or value.endswith('('):
                multi = 1
                opener = value[-1]
                closer = '>' if opener == '<' else ')'
                value = value[:-1] + '...'
            stack[-1]['props'][m.group(1)] = value
    return root


def walk(node, out):
    for k in node['kids']:
        out.append(k)
        walk(k, out)


def short(props, keys):
    parts = []
    for key in keys:
        if key in props:
            parts.append('%s=%s' % (key, props[key]))
    return ', '.join(parts)


def main():
    files = []
    for base, _, names in os.walk(ROOT):
        for n in names:
            if n.endswith('.dfm'):
                files.append(os.path.join(base, n))
    files.sort()
    total = 0
    out = ['# TcxGrid audit of MTG Studio v3', '',
           'Generated by `scripts/audit_tcxgrid.py` from the .dfm forms. Read-only = `Options.Editing = False` on a column, '
           '`Properties.ReadOnly = True` on its editor, or `OptionsData.Editing = False` on the view.', '']
    for path in files:
        root = parse(path)
        nodes = []
        walk(root, nodes)
        grids = [n for n in nodes if n['kind'] == 'TcxGrid']
        if not grids:
            continue
        rel = os.path.relpath(path, ROOT)
        form = [n for n in root['kids']][0] if root['kids'] else None
        out.append('## %s (%s)' % (rel, form['name'] + ': ' + form['kind'] if form else '?'))
        out.append('')
        if form:
            out.append('Form caption: %s' % form['props'].get('Caption', '-'))
            out.append('')
        for grid in grids:
            total += 1
            g = grid['props']
            out.append('### %s' % grid['name'])
            out.append('')
            out.append('- grid: Align=%s, %sx%s, Font=%s %s, LookAndFeel.Kind=%s' % (
                g.get('Align', '-'), g.get('Width', '?'), g.get('Height', '?'),
                g.get('Font.Name', '-'), g.get('Font.Height', '-'), g.get('LookAndFeel.Kind', '-')))
            levels = []
            walk(grid, levels)
            views = [n for n in levels if re.match(r'Tcx\w*View$', n['kind']) or n['kind'].endswith('TableView')]
            lvls = [n for n in levels if n['kind'] == 'TcxGridLevel']
            for lv in lvls:
                out.append('- level %s: GridView=%s, Caption=%s' % (lv['name'], lv['props'].get('GridView', '-'), lv['props'].get('Caption', '-')))
            for view in views:
                v = view['props']
                cols = [c for c in view['kids'] if c['kind'] in ('TcxGridColumn', 'TcxGridDBColumn', 'TcxGridBandedColumn', 'TcxGridDBBandedColumn')]
                editing = v.get('OptionsData.Editing', 'True(default)')
                out.append('- view %s (%s): %s' % (view['name'], view['kind'], short(v, VIEW_KEYS) or 'defaults'))
                out.append('  - %d columns; view editing: %s' % (len(cols), editing))
                for c in cols:
                    p = c['props']
                    ro = []
                    if p.get('Options.Editing') == 'False':
                        ro.append('Options.Editing=False')
                    if p.get('Properties.ReadOnly') == 'True':
                        ro.append('Properties.ReadOnly=True')
                    if p.get('Options.Focusing') == 'False':
                        ro.append('Options.Focusing=False')
                    flag = 'READ-ONLY (%s)' % ', '.join(ro) if ro else ('read-only (view)' if editing == 'False' else 'editable')
                    out.append('    - %s [%s]: %s' % (c['name'], flag, short(p, COL_KEYS)))
            out.append('')
    out.append('Total TcxGrid controls: %d' % total)
    sys.stdout.write('\n'.join(out) + '\n')


main()
