// Generates lib/e/text/emoji_seq.e: the strings of the RegExp properties of strings (Basic_Emoji and the RGI_Emoji_* sequence
// families). The sequences are read from the matchStrings of test262's generated property-escape tests, whose directory is the
// argument:
//
//   node scripts/gen_emoji_seq.mjs D:/Temp/test262/test/built-ins/RegExp/property-escapes/generated/strings
//
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = process.argv[2];
if (!dir) throw new Error('usage: node scripts/gen_emoji_seq.mjs <test262 property-escapes/generated/strings directory>');
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'lib', 'e', 'text', 'emoji_seq.e');
const names = ['Basic_Emoji', 'RGI_Emoji_Flag_Sequence', 'RGI_Emoji_Modifier_Sequence', 'RGI_Emoji_Tag_Sequence', 'RGI_Emoji_ZWJ_Sequence'];

function esc(bytes) {
  let s = '';
  for (const b of bytes) {
    if (b === 0x22) s += '\\"';
    else if (b === 0x5c) s += '\\\\';
    else if (b >= 0x20 && b < 0x7f) s += String.fromCharCode(b);
    else s += '\\x' + b.toString(16).padStart(2, '0');
  }
  return s;
}

function strings(name) {
  const text = readFileSync(join(dir, name + '.js'), 'utf8');
  const at = text.indexOf('matchStrings: [');
  const end = text.indexOf('\n  ],', at);
  const list = text.slice(at + 'matchStrings: ['.length, end);
  return [...list.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map((m) => (0, eval)('"' + m[1] + '"'));
}

// A sequence is its code points as 3-byte little-endian values; sequences are separated by 0xFFFFFF.
let src = '// Strings of the RegExp properties of strings, generated by scripts/gen_emoji_seq.mjs -- edit the generator, not this file.\n';
src += '// Each sequence is 3-byte little-endian code points; 0xFFFFFF ends a sequence.\n\n';
let fns = '';
names.forEach((name, i) => {
  const bytes = [];
  for (const s of strings(name)) {
    for (const ch of s) { const c = ch.codePointAt(0); bytes.push(c & 255, (c >> 8) & 255, (c >> 16) & 255); }
    bytes.push(255, 255, 255);
  }
  src += 'fn s' + i + '() -> str { ret "' + esc(bytes) + '" }\n';
  fns += '    if str.eq(name, "' + name + '") { ret s' + i + '() }\n';
});
src = src.replace('\n\nfn s0', '\n\nuse e.str\n\nfn s0');
src += '\n// The sequences of the named property of strings, or "" when there is none.\nfn sequences(name: str) -> str {\n' + fns + '    ret ""\n}\n';
writeFileSync(out, src);
console.log('wrote', out, src.length, 'bytes');
