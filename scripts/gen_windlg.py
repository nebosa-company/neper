"""Bakes the artwork of v3's dialog bodies into lib/e/ui/windlg.e from ref/windows-1to1/dialogs: the Options category icons (16 x 16, transparent where
the pixel is the button's fill) and the Options header's check icon (16 x 16 opaque, on the gradient). Edit this script, not the generated file.
Run from the repository root with python -I."""
from PIL import Image
import numpy as np

D = 'docs/ui/looks/ref/windows-1to1/dialogs/'
o = np.array(Image.open(D + 'options-01-interface@1x.png').convert('RGB')).astype(int)
CAP = 576
arts = []


def keyed(im, x, y, w, h, bg):
    out = []
    for yy in range(y, y + h):
        for xx in range(x, x + w):
            p = tuple(int(v) for v in im[yy, xx])
            out.append(0 if p == bg else 0xFF000000 | (p[0] << 16) | (p[1] << 8) | p[2])
    return (w, h, out)


def opaque(im, x, y, w, h):
    return (w, h, [0xFF000000 | (int(im[yy, xx][0]) << 16) | (int(im[yy, xx][1]) << 8) | int(im[yy, xx][2]) for yy in range(y, y + h) for xx in range(x, x + w)])


for i in range(11):
    y0 = 37 + 36 * i
    bg = (0xAC, 0xBF, 0xE8) if i == 0 else (255, 255, 255)
    arts.append(keyed(o, 20, y0 + 8, 16, 16, bg))
arts.append(opaque(o, 695, 41, 16, 16))

src = '// Generated by scripts/gen_windlg.py from ref/windows-1to1/dialogs; edit the script.\n\n'
src += 'fn art_count() -> usize { ret %dusize }\n' % len(arts)
src += 'fn art_w(id: usize) -> usize {\n'
for i, (w, h, px) in enumerate(arts):
    src += '    if id == %dusize { ret %dusize }\n' % (i, w)
src += '    ret 0usize\n}\n'
src += 'fn art_h(id: usize) -> usize {\n'
for i, (w, h, px) in enumerate(arts):
    src += '    if id == %dusize { ret %dusize }\n' % (i, h)
src += '    ret 0usize\n}\n'
src += 'fn art(id: usize) -> [%d]u32 {\n    var out: [%d]u32 = zero\n' % (CAP, CAP)
for i, (w, h, px) in enumerate(arts):
    src += '    if id == %dusize { ret [%d]u32{ %s } }\n' % (i, CAP, ', '.join('0x%08Xu32' % v for v in px + [0] * (CAP - len(px))))
src += '    ret out\n}\n'
open('lib/e/ui/windlg.e', 'w', encoding='utf-8').write(src)
