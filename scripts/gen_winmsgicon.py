"""Bakes the native Windows 11 message box question icon (32 x 33 px at 100 %) into lib/e/ui/winmsgicon.e.
The pixels are cut from docs/ui/looks/ref/windows-native/light/messagebox-active@1x.png (white = not painted)."""
from PIL import Image
im = Image.open('docs/ui/looks/ref/windows-native/light/messagebox-active@1x.png').convert('RGB')
x0, y0, w, h = 29, 54, 32, 33
vals = []
for y in range(h):
    for x in range(w):
        r, g, b = im.getpixel((x0 + x, y0 + y))
        vals.append(0 if (r, g, b) == (255, 255, 255) else 0xFF000000 | r << 16 | g << 8 | b)
body = ', '.join('0x%08Xu32' % v for v in vals)
open('lib/e/ui/winmsgicon.e', 'w', newline='\n').write(
    '// GENERATED by scripts/gen_winmsgicon.py from ref/windows-native/light/messagebox-active@1x.png: the native Windows 11\n'
    '// message box question icon, %d x %d, 0xAARRGGBB, alpha 0 = not painted. Edit the script, not this file.\n\n'
    'fn question_w() -> usize { ret %dusize }\nfn question_h() -> usize { ret %dusize }\n'
    'fn question_px() -> [%d]u32 { ret [%d]u32{ %s } }\n' % (w, h, w, h, w * h, w * h, body))
