"""Generates the vector region of tests/selfhost/fixtures/link/db_docstore (L147, D2763).

An independent writer of the documented file format (struct + zlib.crc32) and an independent
replay model: it scripts ten operations, writes the file they must produce byte for byte, and for
every prefix of the log records the state a correct recovery must reach (live documents, events,
marks). The fixture compares `bytes(db)` with the literal and drives `restore` over truncations
and a flipped byte against the model's table.

    python scripts/gen_db_docstore_test.py     # rewrites the region between the markers
"""
import struct
import sys
import zlib
from pathlib import Path

FIXTURE = Path(__file__).resolve().parent.parent / 'tests/selfhost/fixtures/link/db_docstore/src/main.e'


def s(x):
    b = x.encode()
    return struct.pack('<I', len(b)) + b


def frame(payload):
    return struct.pack('<II', len(payload), zlib.crc32(payload) & 0xFFFFFFFF) + payload


def put(coll, id_, data):
    return frame(b'\x01' + s(coll) + s(id_) + s(data))


def delete(coll, id_):
    return frame(b'\x02' + s(coll) + s(id_))


def event(stream, version, kind, data, at):
    return frame(b'\x03' + s(stream) + struct.pack('<I', version) + s(kind) + s(data) + struct.pack('<q', at))


def mark(ns, name, seq):
    return frame(b'\x04' + bytes([ns]) + s(name) + struct.pack('<Q', seq))


OPS = [
    ('put', put('users', 'u1', '{"name":"ada","age":36}')),
    ('put', put('users', 'u2', '{"name":"bob"}')),
    ('put', put('orders', 'o1', '{"total":0}')),
    ('put', put('users', 'u1', '{"name":"ada","age":37}')),
    ('del', delete('users', 'u2')),
    ('ev', event('order-1', 1, 'OrderPlaced', '{"customer":"u1"}', 1000)),
    ('ev', event('order-1', 2, 'ItemAdded', '2', 1001)),
    ('ev', event('order-2', 1, 'OrderPlaced', '{}', 1002)),
    ('ev', event('order-1', 3, 'ItemAdded', '3', 1003)),
    ('mark', mark(1, 'mailer', 2)),
]


def lit(b):
    out = []
    for c in b:
        if 32 <= c < 127 and c not in (34, 92):
            out.append(chr(c))
        else:
            out.append('\\x%02X' % c)
    return '"' + ''.join(out) + '"'


def model(k):
    docs = {}
    events = 0
    marks = {}
    spec = [
        ('put', 'users', 'u1'), ('put', 'users', 'u2'), ('put', 'orders', 'o1'), ('put', 'users', 'u1'),
        ('del', 'users', 'u2'), ('ev',), ('ev',), ('ev',), ('ev',), ('mark', 'mailer'),
    ]
    for op in spec[:k]:
        if op[0] == 'put':
            docs[(op[1], op[2])] = True
        elif op[0] == 'del':
            docs.pop((op[1], op[2]), None)
        elif op[0] == 'ev':
            events += 1
        else:
            marks[op[1]] = True
    return len(docs), events, len(marks)


def main():
    image = b'NDS1' + b''.join(raw for _, raw in OPS)
    ends = []
    pos = 4
    for _, raw in OPS:
        pos += len(raw)
        ends.append(pos)
    out = []
    out.append('fn gen_image() -> str { ret %s }' % lit(image))
    out.append('fn gen_len() -> usize { ret %dusize }' % len(image))
    # frame end offsets and the state after each prefix
    out.append('fn gen_end(k: usize) -> usize {')
    out.append('    if k == 0usize { ret 4usize }')
    for i, e in enumerate(ends):
        out.append('    if k == %dusize { ret %dusize }' % (i + 1, e))
    out.append('    ret 0usize')
    out.append('}')
    out.append('// state after k operations: live documents, events, marks')
    for name, idx in (('docs', 0), ('events', 1), ('marks', 2)):
        out.append('fn gen_%s(k: usize) -> usize {' % name)
        for k in range(0, len(OPS) + 1):
            out.append('    if k == %dusize { ret %dusize }' % (k, model(k)[idx]))
        out.append('    ret 999usize')
        out.append('}')
    out.append('fn gen_ops() -> usize { ret %dusize }' % len(OPS))
    text = FIXTURE.read_text(encoding='utf-8')
    b = text.index('// BEGIN generated')
    e = text.index('// END generated')
    text = text[:b] + '// BEGIN generated by scripts/gen_db_docstore_test.py\n' + '\n'.join(out) + '\n' + text[e:]
    FIXTURE.write_bytes(text.encode('utf-8'))
    print('image', len(image), 'bytes,', len(OPS), 'frames; ends', ends)


if __name__ == '__main__':
    sys.exit(main())
