# Writes lib/e/gfx/maxchroma_table.e from colorspace::max_chroma_table (hue 0..360 fastest, luminance 0..100 slowest).
suppressMessages(library(colorspace))
t <- colorspace::max_chroma_table
stopifnot(length(t) == 361 * 101)
hs <- rep(0:360, times = 101); ls <- rep(0:100, each = 361)
stopifnot(identical(names(t), paste(hs, ls, sep = "-")))
con <- file("lib/e/gfx/maxchroma_table.e", "w")
writeLines(c(sprintf("// Generated by scripts/gen_maxchroma_table.R from R's colorspace %s. Do not edit.", as.character(packageVersion("colorspace"))),
  "// max_chroma_table: 361 hues (0 to 360, fastest) by 101 luminances (0 to 100), space separated.",
  paste0("fn values() -> str { ret \"", paste(sprintf("%.17g", as.numeric(t)), collapse = " "), "\" }")), con)
close(con)
