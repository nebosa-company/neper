"""Bakes v3's grid pictures into lib/e/ui/winsetpic.e from the 1:1 captures: the Mirage set symbol and the Time Spiral Timeshifted disc of the collection
grid (ref/windows-1to1/data_grid_bottom.png, 20 x 17 px, 0xAARRGGBB; the symbol is translucent, so its alpha and colour are solved from the white and the grey
rows) and the 18 command icons of the Shortcuts grid (ref/windows-1to1/data_grid_shortcuts_hover.png, rows 0 to 17, 21 x 16 px, alpha 0 where the pixel is the row's face).
Edit this script, not the generated file."""
from PIL import Image
import numpy as np

r = np.array(Image.open('docs/ui/looks/ref/windows-1to1/data_grid_bottom.png').convert('RGB')).astype(float)
X0, W, H = 25, 20, 17  # the picture node stands one pixel below the row's first row, so the tiles start at row 1
white = np.mean([r[y:y + H, X0:X0 + W] for y in (72, 110, 148, 186)], axis=0)
grey = np.mean([r[y:y + H, X0:X0 + W] for y in (129, 167)], axis=0)
alpha = np.clip(1.0 - (white - grey).mean(axis=2) / 16.0, 0.0, 1.0)
mar = []
for y in range(H):
    for x in range(W):
        a = alpha[y, x]
        if a < 0.06:
            mar.append(0)
            continue
        c = np.clip((white[y, x] - (1.0 - a) * 255.0) / a, 0, 255).round().astype(int)
        mar.append((int(round(a * 255)) << 24) | (c[0] << 16) | (c[1] << 8) | c[2])
tmt = []
for y in range(H):
    for x in range(W):
        p = r[53 + y, X0 + x].astype(int)
        tmt.append(0 if tuple(p) == (239, 239, 239) else 0xFF000000 | (p[0] << 16) | (p[1] << 8) | p[2])
s = np.array(Image.open('docs/ui/looks/ref/windows-1to1/data_grid_shortcuts_hover.png').convert('RGB')).astype(int)
SW, SH, N = 21, 16, 18
sc = []
for row in range(N):
    top = 53 + 18 * row
    face = (213, 228, 238) if row == 0 else ((255, 255, 255) if row % 2 == 1 else (239, 239, 239))
    for y in range(SH):
        for x in range(SW):
            yy = top + y
            if yy >= 366:
                sc.append(0)
                continue
            p = s[yy, 13 + x]
            sc.append(0 if tuple(p) == face else 0xFF000000 | (p[0] << 16) | (p[1] << 8) | p[2])
lit = lambda v: ', '.join('0x%08Xu32' % q for q in v)
open('lib/e/ui/winsetpic.e', 'w', newline='\n').write(
    "// GENERATED by scripts/gen_winsetpic.py from ref/windows-1to1 (data_grid_bottom, data_grid_shortcuts_hover): v3's collection set pictures (20 x 18) and the Shortcuts grid's command icons (21 x 17, 18 rows).\n"
    "// 0xAARRGGBB, alpha 0 = the row face. Edit the script, not this file.\n\n"
    "fn set_w() -> usize { ret 20usize }\nfn set_h() -> usize { ret 17usize }\n"
    "fn mar() -> [%d]u32 { ret [%d]u32{ %s } }\nfn tmt() -> [%d]u32 { ret [%d]u32{ %s } }\n"
    "fn cmd_w() -> usize { ret 21usize }\nfn cmd_h() -> usize { ret 16usize }\nfn cmd_count() -> usize { ret 18usize }\n"
    "fn cmd() -> [%d]u32 { ret [%d]u32{ %s } }\n" % (len(mar), len(mar), lit(mar), len(tmt), len(tmt), lit(tmt), len(sc), len(sc), lit(sc)))

# the navigator's hot buttons (22 x 23, "RRGGBB" per pixel) of the 1:1 captures: next (hover4 cell 0), next page (hover4 cell 1), the funnel (hover5 cell 0)
def nav(sheet, left, w=22):
    im = Image.open('docs/ui/looks/ref/windows-1to1/%s.png' % sheet).convert('RGB')
    return ''.join('%02X%02X%02X' % im.getpixel((left + x, 221 + y)) for y in range(23) for x in range(w))
hot = {3: nav('data_grid_hover4', 149), 4: nav('data_grid_hover4', 757), 7: nav('data_grid_hover5', 216, 21)}
open('lib/e/ui/winsetpic.e', 'a', newline='\n').write(
    'fn nav_hot(slot: usize) -> str {\n' + ''.join('    if slot == %dusize { ret "%s" }\n' % (k, v) for k, v in hot.items()) + '    ret ""\n}\n')
