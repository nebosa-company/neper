# Writes lib/e/algo/stat/labramp_data.e: the raw colour tables behind the continuous ggsci palettes (rgb_gsea, rgb_material, rgb_tw3), one set:palette|#RRGGBB,... row each.
.libPaths(c(Sys.getenv("R_ORACLE_LIB"), .libPaths()))
suppressMessages(library(ggsci))
db <- ggsci:::ggsci_db
rows <- character()
for (set in c("gsea", "material", "tw3")) for (p in names(db[[set]])) rows[[length(rows) + 1]] <- paste0(set, ":", p, "|", paste(toupper(unname(db[[set]][[p]])), collapse = ","))
cat("ROWS", length(rows), "\n")
writeLines(c("// generated by scripts/gen_palettes_ramp.R from ggsci: one palette per line, set:palette|#RRGGBB,#RRGGBB,...", "",
             paste0("fn rows() -> str { ret \"", paste0(paste(rows, collapse = "\\n"), "\\n"), "\" }")), "lib/e/algo/stat/labramp_data.e")
