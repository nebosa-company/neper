"""Generate tests/selfhost/fixtures/link/fmt_magic/src/main.e (L135, D2801).

Each table row yields samples (the row's bytes with wildcards filled at random, then a
random tail) whose expected answer is the first matching row of an independent Python
scan of the same table; the samples are also given to `filetype` and `puremagic`, and the
generator prints where either names a different type (the fixture records only the table
model, the cross-check is the audit trail in the decision row).
"""
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import fixture_common as fc  # noqa: E402
from magic_table import TABLE  # noqa: E402

random.seed(139)
ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'tests' / 'selfhost' / 'fixtures' / 'link' / 'fmt_magic' / 'src' / 'main.e'


def matches(row, data):
    off, hx = row[0], row[1]
    n = len(hx) // 2
    if off + n > len(data):
        return False
    for i in range(n):
        pair = hx[2 * i:2 * i + 2]
        if pair != '??' and data[off + i] != int(pair, 16):
            return False
    return True


def model(data):
    for row in TABLE:
        if matches(row, data):
            return row
    return None


def sample(row, tail):
    off, hx = row[0], row[1]
    n = len(hx) // 2
    buf = bytearray(random.getrandbits(8) for _ in range(off + n + tail))
    for i in range(n):
        pair = hx[2 * i:2 * i + 2]
        if pair != '??':
            buf[off + i] = int(pair, 16)
    return bytes(buf)


lines = []
mismatch = []
try:
    import filetype
    import puremagic
except ImportError:
    filetype = puremagic = None
for row in TABLE:
    for _ in range(2):
        data = sample(row, random.randint(0, 12))
        hit = model(data)
        lines.append('M %s => %s %s' % (data.hex(), hit[2], hit[3]))
        if filetype:
            g = filetype.guess(data)
            if g is not None and g.mime != hit[2]:
                mismatch.append((hit[4], hit[2], 'filetype', g.mime))
    # a prefix one byte too short for this row never matches it
    data = sample(row, 0)[:row[0] + len(row[1]) // 2 - 1]
    short_hit = model(data)
    lines.append('%s %s => %s' % ('M' if short_hit else 'N', data.hex() or '-', ('%s %s' % (short_hit[2], short_hit[3])) if short_hit else '-'))
for _ in range(60):
    data = bytes(random.getrandbits(8) for _ in range(random.randint(0, 40)))
    hit = model(data)
    lines.append('%s %s => %s' % ('M' if hit else 'N', data.hex() or '-', ('%s %s' % (hit[2], hit[3])) if hit else '-'))
print('cross-check mismatches vs filetype:')
for m in mismatch:
    print('  ', m)

vec, names = fc.vector_functions('v', lines)

CHECK = '''
fn hexval(c: u8) -> u8 {
    if c >= 97u8 { ret c - 87u8 }
    ret c - 48u8
}

fn unhex(s: str, out: []u8) -> usize {
    if s.len == 1usize && s[0usize] == 45u8 { ret 0usize }
    var i = 0usize
    while i + 1usize < s.len {
        out[i / 2usize] = hexval(s[i]) * 16u8 + hexval(s[i + 1usize])
        i += 2usize
    }
    ret s.len / 2usize
}

fn check_line(line: str) -> u8 {
    var data: [320]u8 = zero
    let (kind, p0) = tok(line, 0usize)
    let (hex_text, p1) = tok(line, p0)
    let (arrow, p2) = tok(line, p1)
    let (mime, p3) = tok(line, p2)
    let (ext, p4) = tok(line, p3)
    let n = unhex(hex_text, data[0usize..320usize])
    let (got, found) = magic.sniff(data[0usize..n])
    if kind[0usize] == 78u8 {
        if found { ret 1u8 }
        ret 0u8
    }
    if !found { ret 2u8 }
    if !text_is(got.mime, mime) { ret 3u8 }
    if !text_is(got.extension, ext) { ret 4u8 }
    ret 0u8
}

'''

MAIN = '''fn main(a: *mem.Arena, args: []str) -> err {
    if magic.row_count() != %dusize { os.exit(101i32) }
    let r = run_vectors()
    if r != 0u8 { os.exit(i32(r)) }
    try io.print("fmt magic ok")
    ret ok
}
''' % len(TABLE)

src = ('// e.fmt.magic: every table row sampled twice (wildcards filled at random, random tail), one byte too\n'
       '// short, and random noise, against an independent first-match scan of the same table (D2801).\n'
       '// Generated by scripts/gen_magic_test.py.\n'
       'use e.io\nuse e.mem\nuse e.os\nuse e.fmt.magic\n\n'
       + fc.PRELUDE + CHECK + vec + '\n' + fc.run_all(names, 'check_line') + '\n' + MAIN)
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_bytes(src.encode('utf-8'))
print('wrote', OUT, len(lines), 'vectors')
