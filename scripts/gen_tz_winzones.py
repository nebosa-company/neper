"""Generate lib/e/tz/winzones.e: the Windows time zone name to IANA zone map (L150, D2800).

Source: the CLDR windowsZones primary mapping (territory 001) as shipped in tzlocal's
`windows_tz` (139 Windows names, and the 587 IANA names that map back, many IANA links
sharing one Windows zone). The generated source holds two tables as string chunks.

    PYTHONPATH=<tzlocal install dir> python scripts/gen_tz_winzones.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from tzlocal.windows_tz import win_tz, tz_win  # noqa: E402
import fixture_common as fc  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'lib' / 'e' / 'tz' / 'winzones.e'

forward = sorted((k, v) for k, v in win_tz.items() if k and v)
reverse = sorted((k, v) for k, v in tz_win.items() if k and v)

fsrc, fnames = fc.vector_functions('windows_rows', ['%s=%s' % kv for kv in forward])
rsrc, rnames = fc.vector_functions('iana_rows', ['%s=%s' % kv for kv in reverse])
# The territory rows that differ from the 001 default: `Windows id|TT=iana`, extracted from .NET's
# TimeZoneInfo.TryConvertWindowsIdToIanaId (ICU's CLDR windowsZones) by `scripts/tz_winzones_territories.ps1`.
territory = [l for l in (ROOT / 'scripts' / 'tz_winzones_territories.txt').read_text(encoding='utf-8').split('\n') if l]
tsrc, tnames = fc.vector_functions('territory_rows', territory)


def scan_calls(names):
    out = []
    for n in names:
        out.append('    let (hit_%s, found_%s) = find_row(%s(), key)' % (n, n, n))
        out.append('    if found_%s { ret (hit_%s, ok) }' % (n, n))
    return '\n'.join(out)


src = '''// The Windows time zone name to IANA zone map and back, as NodaTime's
// `TzdbDateTimeZoneSource.WindowsMapping` and .NET's `TimeZoneInfo.TryConvertWindowsIdToIanaId`
// do: a Windows id (`Pacific Standard Time`) names the zone's primary IANA zone
// (`America/Los_Angeles`), and an IANA name (any of its links) names its Windows id.
//
// The table is the CLDR `windowsZones` primary mapping (territory 001) -- one IANA zone per
// Windows id -- and the territory rows that differ from it (`Central Standard Time` in `CA` is
// `America/Winnipeg`); a territory with no row of its own gets the 001 answer, as in .NET.
// Matching is ASCII case-insensitive, both ways. The rows are generated by
// `scripts/gen_tz_winzones.py`.

error NotFound

fn fold(b: u8) -> u8 {
    if b >= 65u8 && b <= 90u8 { ret b + 32u8 }
    ret b
}

fn same_fold(a: str, b: str) -> bool {
    if a.len != b.len { ret false }
    var i = 0usize
    while i < a.len {
        if fold(a[i]) != fold(b[i]) { ret false }
        i += 1usize
    }
    ret true
}

// One `left=right` row per line; the answer is the other side of the matching row.
fn find_row(rows: str, key: str) -> (str, bool) {
    var start = 0usize
    var i = 0usize
    while i < rows.len {
        if rows[i] == 10u8 {
            let row = rows[start..i]
            var eq = 0usize
            while eq < row.len && row[eq] != 61u8 { eq += 1usize }
            if eq < row.len {
                if same_fold(row[0usize..eq], key) { ret (row[eq + 1usize..row.len], true) }
            }
            start = i + 1usize
        }
        i += 1usize
    }
    ret ("", false)
}

fn iana_for_windows(name: str) -> (str, err) {
    let key = name
''' + scan_calls(fnames) + '''
    ret ("", NotFound)
}

// The row `Name|TT=iana` of a Windows id and territory, if there is one.
fn find_territory_row(rows: str, name: str, territory: str) -> (str, bool) {
    var start = 0usize
    var i = 0usize
    while i < rows.len {
        if rows[i] == 10u8 {
            let row = rows[start..i]
            var bar = 0usize
            while bar < row.len && row[bar] != 124u8 { bar += 1usize }
            var eq = bar
            while eq < row.len && row[eq] != 61u8 { eq += 1usize }
            if eq < row.len {
                if same_fold(row[0usize..bar], name) && same_fold(row[bar + 1usize..eq], territory) { ret (row[eq + 1usize..row.len], true) }
            }
            start = i + 1usize
        }
        i += 1usize
    }
    ret ("", false)
}

// The IANA zone of a Windows id in a two-letter territory: the territory's own row, else the
// default one. An empty territory, `001` and one with no row give the default.
fn iana_for_windows_in(name: str, territory: str) -> (str, err) {
''' + '\n'.join(
    '    let (hit_%s, found_%s) = find_territory_row(%s(), name, territory)\n    if found_%s { ret (hit_%s, ok) }' % (n, n, n, n, n)
    for n in tnames) + '''
    let (zone, zone_e) = iana_for_windows(name)
    ret (zone, zone_e)
}

fn territory_row_count() -> usize { ret %dusize }

fn windows_for_iana(name: str) -> (str, err) {
    let key = name
''' % len(territory) + '\n'.join(
    '    let (hit_%s, found_%s) = find_row(%s(), key)\n    if found_%s { ret (hit_%s, ok) }' % (n, n, n, n, n)
    for n in rnames) + '''
    ret ("", NotFound)
}

fn windows_zone_count() -> usize { ret %dusize }

fn iana_name_count() -> usize { ret %dusize }

''' % (len(forward), len(reverse)) + fsrc + '\n' + rsrc + '\n' + tsrc

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_bytes(src.encode('utf-8'))
print('wrote', OUT, len(forward), 'windows ids,', len(reverse), 'IANA names')
