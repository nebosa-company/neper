#!/usr/bin/env python3
"""Generates lib/e/net/uts46_table.e from the Unicode IDNA mapping table (UTS #46).

    python scripts/gen_uts46.py IdnaMappingTable.txt > lib/e/net/uts46_table.e

Fetch the input from https://www.unicode.org/Public/idna/15.0.0/IdnaMappingTable.txt (the version the library's other
Unicode tables follow). A record is seven bytes: the first code point (3 bytes, big endian), the status, the offset of the
mapping in the pool (2 bytes, in entries) and its length; it holds until the next record's start. The pool is code points
of 3 bytes each.
"""
import sys

STATUS = {
    "valid": 0, "ignored": 1, "mapped": 2, "deviation": 3, "disallowed": 4,
    "disallowed_STD3_valid": 5, "disallowed_STD3_mapped": 6,
}

def main(path):
    entries = []  # (start, end, status, mapping tuple)
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            fields = [x.strip() for x in line.split(";")]
            rng = fields[0]
            if ".." in rng:
                lo, hi = rng.split("..")
            else:
                lo = hi = rng
            status = STATUS[fields[1]]
            mapping = tuple(int(x, 16) for x in fields[2].split()) if len(fields) > 2 and fields[2] else ()
            entries.append((int(lo, 16), int(hi, 16), status, mapping))
    entries.sort()
    # Merge neighbours with the same status and mapping.
    merged = []
    for lo, hi, st, mp in entries:
        if merged and merged[-1][2] == st and merged[-1][3] == mp and merged[-1][1] + 1 == lo and not mp:
            merged[-1] = (merged[-1][0], hi, st, mp)
        else:
            merged.append((lo, hi, st, mp))
    pool = []
    index = {}
    records = []
    for lo, hi, st, mp in merged:
        if mp:
            if mp not in index:
                index[mp] = len(pool)
                pool.extend(mp)
            off = index[mp]
        else:
            off = 0
        # A range with a mapping covers one code point per record (mappings in the file are per code point).
        if mp and hi > lo:
            for cp in range(lo, hi + 1):
                records.append((cp, st, off, len(mp)))
        else:
            records.append((lo, st, off, len(mp)))
    assert len(pool) < 65536, len(pool)
    out = []
    out.append("// Generated by scripts/gen_uts46.py from the Unicode 15.0.0 IdnaMappingTable. Do not edit.")
    out.append("")
    rec = bytearray()
    for start, st, off, ln in records:
        rec += bytes([(start >> 16) & 255, (start >> 8) & 255, start & 255, st, (off >> 8) & 255, off & 255, ln])
    pl = bytearray()
    for cp in pool:
        pl += bytes([(cp >> 16) & 255, (cp >> 8) & 255, cp & 255])
    def lit(b):
        return '"' + "".join("\\x%02x" % x for x in b) + '"'
    out.append("fn uts46_count() -> usize { ret %dusize }" % len(records))
    out.append("")
    out.append("fn uts46_records() -> str { ret %s }" % lit(rec))
    out.append("")
    out.append("fn uts46_pool() -> str { ret %s }" % lit(pl))
    sys.stdout.write("\n".join(out) + "\n")

main(sys.argv[1])
