# Writes lib/e/algo/stat/copulatab.e: the smoothing-spline tables copula uses for iRho of the Clayton and Gumbel copulas
# (.claytonRhoNeg, .claytonRhoPos, .gumbelRho: fitted rho at 1001 transformed-parameter points). Run:
#   R_ORACLE_LIB=<dir> Rscript scripts/r_oracle/copula_tables.R
.libPaths(c(Sys.getenv("R_ORACLE_LIB"), .libPaths()))
suppressMessages(library(copula))
ns <- asNamespace("copula")
nums <- function(v) paste(sprintf("%.17g", v), collapse = " ")
out <- c("// Generated by scripts/r_oracle/copula_tables.R from copula 1.1-7: the (transformed parameter, rho) grids behind iRho for Clayton and Gumbel.", "")
for (spec in list(c("clayton_neg", ".claytonRhoNeg"), c("clayton_pos", ".claytonRhoPos"), c("gumbel", ".gumbelRho"))) {
  fm <- get(spec[2], ns)$assoMeasFun$fm
  out <- c(out, sprintf("fn %s_x() -> str { ret \"%s\" }", spec[1], nums(fm$x)), "",
           sprintf("fn %s_y() -> str { ret \"%s\" }", spec[1], nums(fm$ysmth)), "")
}
writeLines(out, "lib/e/algo/stat/copulatab.e")
