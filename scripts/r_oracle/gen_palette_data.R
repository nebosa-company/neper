# Writes lib/e/gfx/palette_data.e from the installed viridisLite and RColorBrewer: the 256 colours
# of each viridis map (as brewed into 8 bits, which is what viridis() ramps through) and every
# ColorBrewer palette at every size. The tables are generated, not typed.
#
#   R_ORACLE_LIB=<dir> Rscript scripts/r_oracle/gen_palette_data.R
if (nzchar(Sys.getenv("R_ORACLE_LIB"))) .libPaths(c(Sys.getenv("R_ORACLE_LIB"), .libPaths()))
library(viridisLite)
library(RColorBrewer)
root <- normalizePath(file.path(dirname(sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value = TRUE)[1])), "..", ".."))

hex6 <- function(cols) paste(tolower(substring(cols, 2, 7)), collapse = "")
out <- c(sprintf("// Generated by scripts/r_oracle/gen_palette_data.R from viridisLite %s and RColorBrewer %s. Do not edit.",
                 packageVersion("viridisLite"), packageVersion("RColorBrewer")),
         "",
         "// 256 colours per option, six hex digits each; option letters A..H as viridisLite names them.")
for (o in LETTERS[1:8]) {
  m <- viridis.map[viridis.map$opt == o, ]
  out <- c(out, sprintf('fn viridis_map_%s() -> str { ret "%s" }', tolower(o), hex6(rgb(m$R, m$G, m$B))))
}
info <- brewer.pal.info
rows <- vapply(rownames(info), function(name) {
  blocks <- vapply(3:info[name, "maxcolors"], function(n) hex6(suppressWarnings(brewer.pal(n, name))), "")
  paste0(name, "|", info[name, "maxcolors"], "|", info[name, "category"], "|", paste(blocks, collapse = ","))
}, "")
out <- c(out, "",
         "// One palette per line: name|max colours|category|the palette at 3, 4, .. max colours, comma separated.",
         sprintf('fn brewer_rows() -> str { ret "%s" }', paste(rows, collapse = ";")))
writeLines(out, file.path(root, "lib", "e", "gfx", "palette_data.e"), useBytes = TRUE)
message("palette_data.e: ", length(rows), " ColorBrewer palettes")
