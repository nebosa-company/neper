# gamlss.dist distribution and quantile functions written in e.algo.stat.gamlssq: "gq" args (fn, mu, sigma, x, nu, tau, extra); x is p for the quantiles; extra is the trials bd of BB, ZABB, ZIBB.
# Distribution: 0 pGPO, 1 pLQNO, 2 pNBF (nu), 3 pNET (nu, tau), 4 pNOF (nu), 5 pPIG2, 6 pST1 (nu, tau; integrate, 1e-6), 7 pZAZIPF, 8 pZINBF (nu, tau), 40 pGU.
# Quantile: 10 qBB, 11 qBNB (nu), 12 qGPO, 13 qLQNO, 14 qNBF (nu), 15 qNET (nu, tau), 16 qNOF (nu), 17 qPIG, 18 qPIG2, 19 qSEP1, 20 qSEP2, 21 qST1, 22 qST2 (these four 1e-6), 23 qST4, 24 qST5,
# 25 qWARING, 26 qZABB (nu, bd), 27 qZABNB (nu, tau), 28 qZALG (mu, sigma), 29 qZAPIG (nu), 30 qZAZIPF, 31 qZIBB (nu, bd), 32 qZIBNB (nu, tau), 33 qZINBF (nu, tau), 34 qZIPF (mu), 35 qZIPIG (nu).
suppressMessages(library(gamlss.dist))
cases <- list()
add <- function(fn, mu, sg, x, nu = 0, tau = 0, ex = 0, want, rel = 1e-9, abs = 1e-12) if (is.finite(want)) cases[[length(cases) + 1]] <<- case("gq", c(fn, mu, sg, x, nu, tau, ex), want, rel = rel, abs = abs)
set.seed(20269101)
for (rep in 1:10) {
  p <- runif(1, 0.01, 0.99)
  mu <- runif(1, 0.5, 6); sg <- runif(1, 0.1, 1.5); k <- rpois(1, mu)
  add(0, mu, sg, k, want = pGPO(k, mu = mu, sigma = sg))
  add(12, mu, sg, p, want = qGPO(p, mu = mu, sigma = sg))
  xx <- rnorm(1, mu, sqrt(mu * (1 + sg * mu)))
  add(1, mu, sg, xx, want = pLQNO(xx, mu = mu, sigma = sg))
  add(13, mu, sg, p, want = qLQNO(p, mu = mu, sigma = sg))
  nf <- sample(1:3, 1) + runif(1, -0.4, 0.4)
  add(2, mu, sg, k, nf, want = pNBF(k, mu = mu, sigma = sg, nu = nf))
  add(14, mu, sg, p, nf, want = qNBF(p, mu = mu, sigma = sg, nu = nf))
  nn <- runif(1, 0.5, 2); nt <- nn + runif(1, 0.6, 3); nm <- rnorm(1); ns <- runif(1, 0.3, 2); nx <- rnorm(1, nm, ns)
  add(3, nm, ns, nx, nn, nt, want = pNET(nx, mu = nm, sigma = ns, nu = nn, tau = nt))
  add(15, nm, ns, p, nn, nt, want = qNET(p, mu = nm, sigma = ns, nu = nn, tau = nt))
  nv <- runif(1, 0, 2)
  add(4, nm, ns, nx, nv, want = pNOF(nx, mu = nm, sigma = ns, nu = nv))
  add(16, nm, ns, p, nv, want = qNOF(p, mu = nm, sigma = ns, nu = nv))
  add(40, abs(nm) + 0.5, ns, abs(nx) + 0.3, want = pGU(abs(nx) + 0.3, mu = abs(nm) + 0.5, sigma = ns))
  add(5, mu, sg, k, want = pPIG2(k, mu = mu, sigma = sg))
  add(18, mu, sg, p, want = qPIG2(p, mu = mu, sigma = sg))
  add(17, mu, sg, p, want = qPIG(p, mu = mu, sigma = sg))
  sv <- rnorm(1); st <- runif(1, 1.5, 3); sx <- rnorm(1, nm, ns)
  add(6, nm, ns, sx, sv, st + 2, want = pST1(sx, mu = nm, sigma = ns, nu = sv, tau = st + 2), rel = 1e-6, abs = 1e-9)
  add(19, nm, ns, p, sv, st, want = qSEP1(p, mu = nm, sigma = ns, nu = sv, tau = st), rel = 1e-6, abs = 1e-8)
  add(20, nm, ns, p, sv, st, want = qSEP2(p, mu = nm, sigma = ns, nu = sv, tau = st), rel = 1e-6, abs = 1e-8)
  add(21, nm, ns, p, sv, st + 2, want = qST1(p, mu = nm, sigma = ns, nu = sv, tau = st + 2), rel = 1e-6, abs = 1e-8)
  add(22, nm, ns, p, sv, st + 2, want = qST2(p, mu = nm, sigma = ns, nu = sv, tau = st + 2), rel = 1e-6, abs = 1e-8)
  nw <- runif(1, 0.5, 6); tw <- runif(1, 0.5, 6)
  add(23, nm, ns, p, nw, tw, want = qST4(p, mu = nm, sigma = ns, nu = nw, tau = tw))
  add(24, nm, ns, p, sv, tw, want = qST5(p, mu = nm, sigma = ns, nu = sv, tau = tw))
  wm <- runif(1, 0.5, 4); ws <- runif(1, 0.1, 0.9); pw <- runif(1, 0.01, 0.97)
  add(25, wm, ws, pw, want = qWARING(pw, mu = wm, sigma = ws))
  bd <- sample(5:20, 1); bm <- runif(1, 0.2, 0.8); bs <- runif(1, 0.1, 1.5); bz <- runif(1, 0.05, 0.5)
  add(10, bm, bs, p, 0, 0, bd, want = qBB(p, mu = bm, sigma = bs, bd = bd))
  add(26, bm, bs, p, bz, 0, bd, want = qZABB(p, mu = bm, sigma = bs, nu = bz, bd = bd))
  add(31, bm, bs, p, bz, 0, bd, want = qZIBB(p, mu = bm, sigma = bs, nu = bz, bd = bd))
  bn <- runif(1, 0.1, 0.9); bt <- runif(1, 0.05, 0.5); bm2 <- runif(1, 0.5, 4); bs2 <- runif(1, 0.2, 1.5)
  add(11, bm2, bs2, p, bn, want = qBNB(p, mu = bm2, sigma = bs2, nu = bn))
  add(27, bm2, bs2, p, bn, bt, want = qZABNB(p, mu = bm2, sigma = bs2, nu = bn, tau = bt))
  add(32, bm2, bs2, p, bn, bt, want = qZIBNB(p, mu = bm2, sigma = bs2, nu = bn, tau = bt))
  zp <- runif(1, 0.05, 0.5)
  add(29, mu, sg, p, zp, want = qZAPIG(p, mu = mu, sigma = sg, nu = zp))
  add(35, mu, sg, p, zp, want = qZIPIG(p, mu = mu, sigma = sg, nu = zp))
  zm <- runif(1, 0.3, 0.9); zs <- runif(1, 0.05, 0.5); zk <- sample(0:8, 1)
  add(28, zm, zs, p, want = qZALG(p, mu = zm, sigma = zs))
  zm2 <- runif(1, 0.5, 3)
  add(30, zm2, zs, p, want = qZAZIPF(p, mu = zm2, sigma = zs))
  add(7, zm2, zs, zk, want = pZAZIPF(zk, mu = zm2, sigma = zs))
  add(34, zm2, 0, p, want = qZIPF(p, mu = zm2))
  add(8, mu, sg, k, nf, zs, want = pZINBF(k, mu = mu, sigma = sg, nu = nf, tau = zs))
  add(33, mu, sg, p, nf, zs, want = qZINBF(p, mu = mu, sigma = sg, nu = nf, tau = zs))
}
emit("gamlss_pq", "gamlss.dist", list(cases))
