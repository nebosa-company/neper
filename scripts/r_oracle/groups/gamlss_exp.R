# gamlss.dist EXP (dEXP, pEXP, qEXP with mu) and RG (dRG, pRG, qRG with mu and sigma). Args: (fn, mu, sigma, x, nu): fn 0 density, 1
# distribution, 2 quantile (x is p for 2); the family is EXP for fn 0..2, RG for fn 3..5 and PARETO2 for fn 6..8 and PARETO1 for fn 9..11 and NO for fn 12..14 and PO for fn 15..17 and GA for fn 18..20 and WEI for fn 21..23 and LOGNO for fn 24..26 and IG for fn 27 (distribution) and ZIP for fn 28 (distribution) and 29 (quantile) and NBI for fn 30 (density), 31 (distribution) and 32 (quantile) (x is p for fn 2, 5, 8, 11, 14 and 17). sigma is unused by EXP; nu (the fifth argument) is the degrees of freedom of TF for fn 33 (density), 34 (distribution) and 35 (quantile), and the power of BCCG for fn 36 (distribution) and 37 (quantile); GP is fn 38 (density), 39 (distribution) and 40 (quantile); BE is fn 41, 42 and 43.
suppressMessages(library(gamlss.dist))
cases <- list()
add <- function(fn, args, want, rel = 1e-10, abs = 1e-14) if (is.finite(want)) cases[[length(cases) + 1]] <<- case(fn, args, want, rel = rel, abs = abs)
set.seed(20261244)
for (rep in 1:30) {
  mu <- runif(1, 0.2, 8); x <- runif(1, 0, 6 * mu); p <- runif(1, 0.001, 0.999)
  sg <- runif(1, 0.3, 3); m2 <- rnorm(1)
  add("ex", c(0, mu, 1, x, 0), dEXP(x, mu = mu))
  add("ex", c(1, mu, 1, x, 0), pEXP(x, mu = mu))
  add("ex", c(2, mu, 1, p, 0), qEXP(p, mu = mu))
  add("ex", c(3, m2, sg, x, 0), dRG(x, mu = m2, sigma = sg))
  add("ex", c(4, m2, sg, x, 0), pRG(x, mu = m2, sigma = sg))
  add("ex", c(5, m2, sg, p, 0), qRG(p, mu = m2, sigma = sg))
  pm <- runif(1, 0.3, 5); ps <- runif(1, 0.4, 3); px <- runif(1, 0, 8) * pm
  add("ex", c(6, pm, ps, px, 0), dPARETO2(px, mu = pm, sigma = ps))
  add("ex", c(7, pm, ps, px, 0), pPARETO2(px, mu = pm, sigma = ps))
  add("ex", c(8, pm, ps, p, 0), qPARETO2(p, mu = pm, sigma = ps))
  add("ex", c(9, pm, 1, px / pm, 0), dPARETO1(px / pm, mu = pm))
  add("ex", c(10, pm, 1, px / pm, 0), pPARETO1(px / pm, mu = pm))
  add("ex", c(11, pm, 1, p, 0), qPARETO1(p, mu = pm))
  nm <- rnorm(1); ns <- runif(1, 0.3, 3); nx <- rnorm(1, nm, ns)
  add("ex", c(12, nm, ns, nx, 0), dNO(nx, mu = nm, sigma = ns))
  add("ex", c(13, nm, ns, nx, 0), pNO(nx, mu = nm, sigma = ns))
  add("ex", c(14, nm, ns, p, 0), qNO(p, mu = nm, sigma = ns))
  pl <- runif(1, 0.5, 12); pk <- rpois(1, pl)
  add("ex", c(15, pl, 1, pk, 0), dPO(pk, mu = pl))
  add("ex", c(16, pl, 1, pk, 0), pPO(pk, mu = pl))
  add("ex", c(17, pl, 1, p, 0), qPO(p, mu = pl))
  gm <- runif(1, 0.3, 6); gs <- runif(1, 0.2, 1.5); gx <- rgamma(1, 1 / gs^2, scale = gm * gs^2)
  add("ex", c(18, gm, gs, gx, 0), dGA(gx, mu = gm, sigma = gs))
  add("ex", c(19, gm, gs, gx, 0), pGA(gx, mu = gm, sigma = gs))
  add("ex", c(20, gm, gs, p, 0), qGA(p, mu = gm, sigma = gs))
  ws <- runif(1, 0.6, 4); wx <- rweibull(1, ws, gm)
  add("ex", c(21, gm, ws, wx, 0), dWEI(wx, mu = gm, sigma = ws))
  add("ex", c(22, gm, ws, wx, 0), pWEI(wx, mu = gm, sigma = ws))
  add("ex", c(23, gm, ws, p, 0), qWEI(p, mu = gm, sigma = ws))
  lx <- exp(rnorm(1, nm, ns))
  add("ex", c(24, nm, ns, lx, 0), dLOGNO(lx, mu = nm, sigma = ns))
  add("ex", c(25, nm, ns, lx, 0), pLOGNO(lx, mu = nm, sigma = ns))
  add("ex", c(26, nm, ns, p, 0), qLOGNO(p, mu = nm, sigma = ns))
  ix <- gx * 0.8 + 0.05
  add("ex", c(27, gm, gs, ix, 0), pIG(ix, mu = gm, sigma = gs))
  zs <- runif(1, 0.02, 0.6)
  add("ex", c(28, pl, zs, pk, 0), pZIP(pk, mu = pl, sigma = zs))
  add("ex", c(29, pl, zs, p, 0), qZIP(p, mu = pl, sigma = zs))
  nk <- rnbinom(1, size = 1 / gs, mu = pl)
  add("ex", c(30, pl, gs, nk, 0), dNBI(nk, mu = pl, sigma = gs))
  add("ex", c(31, pl, gs, nk, 0), pNBI(nk, mu = pl, sigma = gs))
  add("ex", c(32, pl, gs, p, 0), qNBI(p, mu = pl, sigma = gs))
  tn <- runif(1, 1.5, 30); tx <- nm + ns * rt(1, tn)
  add("ex", c(33, nm, ns, tx, tn), dTF(tx, mu = nm, sigma = ns, nu = tn))
  add("ex", c(34, nm, ns, tx, tn), pTF(tx, mu = nm, sigma = ns, nu = tn))
  add("ex", c(35, nm, ns, p, tn), qTF(p, mu = nm, sigma = ns, nu = tn))
  bn <- rnorm(1, 0, 1.2)
  add("ex", c(36, gm, gs, gx, bn), pBCCG(gx, mu = gm, sigma = gs, nu = bn))
  add("ex", c(37, gm, gs, p, bn), qBCCG(p, mu = gm, sigma = gs, nu = bn))
  gps <- runif(1, 0.8, 4)
  add("ex", c(38, gm, gps, gx, 0), dGP(gx, mu = gm, sigma = gps))
  add("ex", c(39, gm, gps, gx, 0), pGP(gx, mu = gm, sigma = gps))
  add("ex", c(40, gm, gps, p, 0), qGP(p, mu = gm, sigma = gps))
  bm <- runif(1, 0.1, 0.9); bs <- runif(1, 0.1, 0.8); bx <- rbeta(1, bm * (1 - bs^2) / bs^2, (1 - bm) * (1 - bs^2) / bs^2)
  add("ex", c(41, bm, bs, bx, 0), dBE(bx, mu = bm, sigma = bs))
  add("ex", c(42, bm, bs, bx, 0), pBE(bx, mu = bm, sigma = bs))
  add("ex", c(43, bm, bs, p, 0), qBE(p, mu = bm, sigma = bs))
}
emit("gamlss_exp", "gamlss.dist", list(cases))
