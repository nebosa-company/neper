from PIL import Image
from pathlib import Path

R = Path(__file__).resolve().parents[2] / 'docs/ui/looks/ref/linux/light/dropdown-open@1x.png'
im = Image.open(R).convert('RGBA')
W, H = im.size
BX0, BY0, BX1, BY1 = 24, 28, 182, 145   # the body rectangle [x0, x1) x [y0, y1)


def shadow(x, y):
    r, g, b, a = im.getpixel((x, y))
    if a == 255:
        return 0
    A = a / 255.0
    c = r * A / 255.0
    if c >= 0.999:
        return 0
    return max(0, min(255, round((A - c) / (1 - c) * 255)))


def tile(x0, y0, w, h):
    return ''.join('%02X' % shadow(x, y) for y in range(y0, y0 + h) for x in range(x0, x0 + w))


tl = tile(0, 0, 36, 40)
tr = tile(W - 36, 0, 36, 40)
bl = tile(0, H - 38, 36, 38)
br = tile(W - 36, H - 38, 36, 38)
left = ''.join('%02X' % shadow(x, 85) for x in range(0, 24))
right = ''.join('%02X' % shadow(x, 85) for x in range(182, 206))
top = ''.join('%02X' % shadow(103, y) for y in range(0, 28))
bottom = ''.join('%02X' % shadow(103, y) for y in range(145, 171))
src = '''// The soft shadow of a libadwaita 1.5 popover (the 1 px rim and the blur round `popover > contents`, 12 px corners): the alpha of black
// round the 158 x 117 popover of ref/linux/light/dropdown-open (the same in Dark), with the body's own anti-aliased edge taken out, as a
// 9-slice. The corners are 36 x 40 (top) and 36 x 38 (bottom) alpha bytes as hex; the edges are one alpha per px of the margin
// (24 left and right, 28 above, 26 below), laid along the straight sides. Generated by scripts/linux/gen_shadow_l2.py.

use e.gfx.geometry
use e.gfx.paint
use e.gfx.scene
use e.mem
use e.ui.layout as ui_layout
use e.ui.style
use e.ui.winpx
use e.ui.widget

fn corner_tl() -> str { ret "%s" }
fn corner_tr() -> str { ret "%s" }
fn corner_bl() -> str { ret "%s" }
fn corner_br() -> str { ret "%s" }
fn edge_left() -> str { ret "%s" }
fn edge_right() -> str { ret "%s" }
fn edge_top() -> str { ret "%s" }
fn edge_bottom() -> str { ret "%s" }

fn digit(c: u8) -> u32 {
    if c >= 65u8 { ret u32(c) - 55u32 }
    ret u32(c) - 48u32
}

fn alpha_at(text: str, i: usize) -> f32 {
    ret f32(digit(text[2usize * i]) * 16u32 + digit(text[2usize * i + 1usize])) / 255.0
}

fn measure(ctx: *void, limits: ui_layout.Constraints) -> geometry.Size {
    ret geometry.Size { width: 0.0, height: 0.0 }
}

fn black(alpha: f32) -> paint.Color {
    ret paint.rgba(0.0, 0.0, 0.0, alpha)
}

// A w x h block of alpha bytes with its top left at (x0, y0), every pixel whole (winpx.fill).
fn block(b: *scene.Builder, text: str, w: usize, h: usize, x0: f32, y0: f32) -> err {
    var r = 0usize
    while r < h {
        var c = 0usize
        while c < w {
            let alpha = alpha_at(text, r * w + c)
            if alpha <= 0.0 {
                c += 1usize
                continue
            }
            var run = 1usize
            while c + run < w && alpha_at(text, r * w + c + run) == alpha { run += 1usize }
            try winpx.fill(b, x0 + f32(c), y0 + f32(r), f32(run), 1.0, black(alpha))
            c += run
        }
        r += 1usize
    }
    ret ok
}

type Spec = struct { w: f32, h: f32, dx: f32, dy: f32, body: paint.Color }

fn paint_shadow(ctx: *void, b: *scene.Builder, area: geometry.Rect) -> err {
    let spec = mem.cast[*Spec](ctx)
    // The popover's first whole row and column and its whole size: a fractional top or bottom edge is the body's own anti-aliasing.
    let edge_x = area.x - spec.dx
    let edge_y = area.y - spec.dy
    let x0 = f32(i64(edge_x + 0.999))
    let y0 = f32(i64(edge_y + 0.999))
    let w = f32(i64(edge_x + spec.w)) - x0
    let h = f32(i64(edge_y + spec.h)) - y0
    // The straight sides first, between the corners' 12 px.
    var k = 0usize
    while k < 24usize {
        let left = alpha_at(edge_left(), k)
        if left > 0.0 { try winpx.fill(b, x0 - 24.0 + f32(k), y0 + 12.0, 1.0, h - 24.0, black(left)) }
        let right = alpha_at(edge_right(), k)
        if right > 0.0 { try winpx.fill(b, x0 + w + f32(k), y0 + 12.0, 1.0, h - 24.0, black(right)) }
        k += 1usize
    }
    k = 0usize
    while k < 28usize {
        let top = alpha_at(edge_top(), k)
        if top > 0.0 { try winpx.fill(b, x0 + 12.0, y0 - 28.0 + f32(k), w - 24.0, 1.0, black(top)) }
        k += 1usize
    }
    k = 0usize
    while k < 26usize {
        let bottom = alpha_at(edge_bottom(), k)
        if bottom > 0.0 { try winpx.fill(b, x0 + 12.0, y0 + h + f32(k), w - 24.0, 1.0, black(bottom)) }
        k += 1usize
    }
    try block(b, corner_tl(), 36usize, 40usize, x0 - 24.0, y0 - 28.0)
    try block(b, corner_tr(), 36usize, 40usize, x0 + w - 12.0, y0 - 28.0)
    try block(b, corner_bl(), 36usize, 38usize, x0 - 24.0, y0 + h - 12.0)
    try block(b, corner_br(), 36usize, 38usize, x0 + w - 12.0, y0 + h - 12.0)
    // GTK lays the popover out on a fraction of a pixel: its top row is 93 %% covered by the body and the row under it 85 %%.
    try winpx.fill(b, x0 + 12.0, y0 - 1.0, w - 24.0, 1.0, paint.rgba(spec.body.red, spec.body.green, spec.body.blue, 0.926))
    ret winpx.fill(b, x0 + 12.0, y0 + h, w - 24.0, 1.0, paint.rgba(spec.body.red, spec.body.green, spec.body.blue, 0.85))
}

// A zero-size node, first in the popover's column, that paints the shadow round the `w` x `h` popover whose content box starts
// (`dx`, `dy`) inside it (its padding): the node's own top left is that content origin. `body` is the popover's colour.
fn node(a: *mem.Arena, w: f32, h: f32, dx: f32, dy: f32, body: paint.Color) -> (widget.Node, err) {
    var s = style.defaults()
    s.width = style.Length { Px: 0.0 }
    s.height = style.Length { Px: 0.0 }
    var none: []const widget.Node = zero
    let (specs, specs_error) = mem.alloc[Spec](a, 1usize)
    if specs_error != ok { ret (zero, specs_error) }
    specs[0usize] = Spec { w: w, h: h, dx: dx, dy: dy, body: body }
    ret (widget.Node { key: 0u64, kind: widget.Kind { Custom: widget.Custom { ctx: mem.cast[*void](&specs[0usize]), measure: measure, paint: paint_shadow, state: widget.bytes_of[Spec](&specs[0usize]) } }, style: s, children: none }, ok)
}
''' % (tl, tr, bl, br, left, right, top, bottom)
(Path(__file__).resolve().parents[2] / 'lib/e/ui/linuxshadow_l2.e').write_text(src, encoding='utf-8')
print(len(src), [x for x in (left, right, top, bottom)])
