#!/usr/bin/env python3
"""Reads isoband's isoband.cpp (the switch in isobander::calculate_contour) and writes
lib/e/gfx/isoband_table.e: its 81 cases as one string, so e.gfx.isoband holds the table, not a
transcription of 900 lines of C++.

  python scripts/gen_isoband_table.py <isoband.cpp> > lib/e/gfx/isoband_table.e

A case is `N:K:V0|V1|V2;` where K is 0 (one variant), 1 (vc < vlo picks V0, else V1), 2 (vc >= vhi
picks V0, else V1) or 3 (vc < vlo V0, vc >= vhi V1, else V2); a variant is polygons separated by
`.`, a polygon is its points, and a point is one letter, 'a' + (dr * 2 + dc) * 5 + type, with the
types grid, hintersect_lo, hintersect_hi, vintersect_lo, vintersect_hi as 0 to 4.
"""
import re
import sys

TYPES = {"grid": 0, "hintersect_lo": 1, "hintersect_hi": 2, "vintersect_lo": 3, "vintersect_hi": 4}


def offsets(expr):
    expr = expr.strip()
    return {"r": (0, 0), "r+1": (1, 0), "c": (0, 0), "c+1": (0, 1)}[expr]


def point(args):
    r, c, t = [a.strip() for a in args.split(",")]
    dr = {"r": 0, "r+1": 1}[r]
    dc = {"c": 0, "c+1": 1}[c]
    return chr(ord("a") + (dr * 2 + dc) * 5 + TYPES[t])


def main(path):
    src = open(path, encoding="utf-8").read().split("\n")
    start = next(i for i, l in enumerate(src) if "switch(cells[r + c * (nrow - 1)])" in l) + 1
    text = []
    depth = 1
    for l in src[start:]:
        l = re.sub(r"//.*", "", l)
        depth += l.count("{") - l.count("}")
        if depth <= 0:
            break
        text.append(l)
    body = " ".join(text)
    tokens = re.findall(r"case \d+:|poly_start\([^)]*\);|poly_add\([^)]*\);|poly_merge\(\);|double vc = [^;]*;|"
                        r"\} else if \([^)]*\) \{|\} else \{|if \([^)]*\) \{|break;|\{|\}", body)
    cases = {}
    cur = None
    variants = None
    variant = None
    poly = None
    kind = 0
    stack = []
    for t in tokens:
        if t.startswith("case"):
            cur = int(t[4:-1])
            variants = [[]]
            variant = variants[0]
            kind = 0
            cases[cur] = (kind, variants)
            poly = None
        elif t.startswith("poly_start"):
            poly = [point(t[len("poly_start("):-2])]
        elif t.startswith("poly_add"):
            poly.append(point(t[len("poly_add("):-2]))
        elif t.startswith("poly_merge"):
            variant.append("".join(poly))
            poly = None
        elif t.startswith("double vc"):
            pass
        elif t.startswith("if ("):
            cond = re.search(r"\(vc (<|>=) (vlo|vhi)\)", t).groups()
            kind = 1 if cond == ("<", "vlo") else 2
            cases[cur] = (kind, variants)
            stack.append("if")
        elif t.startswith("} else if"):
            cond = re.search(r"\(vc (<|>=) (vlo|vhi)\)", t).groups()
            assert cond == (">=", "vhi") and kind == 1, t
            kind = 3
            cases[cur] = (kind, variants)
            variants.append([])
            variant = variants[-1]
        elif t.startswith("} else"):
            variants.append([])
            variant = variants[-1]
        elif t == "{":
            stack.append("blk")
        elif t == "}":
            stack.pop()
        elif t == "break;":
            pass
        if t.startswith("if ("):
            pass
    # the first `if` variant is variants[0]; `variants` starts with one list, so the first branch writes to it
    out = []
    for n in sorted(cases):
        kind, variants = cases[n]
        if kind == 0:
            vs = [variants[0]]
        else:
            vs = variants
        want = {0: 1, 1: 2, 2: 2, 3: 3}[kind]
        assert len(vs) == want, (n, kind, len(vs))
        out.append("%d:%d:%s;" % (n, kind, "|".join(".".join(v) for v in vs)))
    table = "".join(out)
    print("// Generated by scripts/gen_isoband_table.py from isoband's isoband.cpp (the switch over the 81 ternary cell codes).")
    print("// Format: see the script's docstring.")
    print("")
    print("fn band_table() -> str {")
    chunks = [table[i:i + 100] for i in range(0, len(table), 100)]
    print('    ret "' + '" +\n        "'.join(chunks) + '"' if False else '    ret "' + table + '"')
    print("}")


main(sys.argv[1])
