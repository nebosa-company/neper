"""Writes lib/e/text/ansi_tables.e from cli's graphbreak.h and charwidth.h.

    python scripts/gen_cli_tables.py <cli source dir>/src

The two headers are cli's two-stage Unicode tables (Grapheme_Break and East_Asian_Width classes,
128-code-point blocks); e.text.ansi counts graphemes and display widths with exactly them, so a
count equals cli's whatever Unicode version e.text.segment carries. Each table becomes functions
returning string chunks, because one 40 000 character literal is more than a source line should
be: stage 1 as two hex digits per block, stage 2 as one base-36 digit per code point.
"""
import re
import sys
from pathlib import Path

CHUNK = 4096
src = Path(sys.argv[1])
out = Path(__file__).resolve().parent.parent / "lib" / "e" / "text" / "ansi_tables.e"


def numbers(text, name):
    body = text[text.index(name):]
    body = body[body.index("{"):]
    depth, end = 0, 0
    for i, c in enumerate(body):
        depth += c == "{"
        depth -= c == "}"
        if depth == 0:
            end = i
            break
    body = re.sub(r"/\*.*?\*/", "", body[: end + 1], flags=re.S)
    return [int(n) for n in re.findall(r"-?\d+", body)]


def chunks(fn, text):
    lines = [f"fn {fn}(k: usize) -> str {{"]
    for k in range(0, len(text), CHUNK):
        lines.append(f'    if k == {k // CHUNK}usize {{ ret "{text[k:k + CHUNK]}" }}')
    lines += ['    ret ""', "}", ""]
    return lines


def b36(v):
    return "0123456789abcdefghijklmnopqrstuvwxyz"[v]


gb = (src / "graphbreak.h").read_text()
cw = (src / "charwidth.h").read_text()
lines = [
    "// Generated by scripts/gen_cli_tables.py from cli's graphbreak.h and charwidth.h. Do not edit.",
    "",
    f"const CHUNK: usize = {CHUNK}usize",
    "",
]
for name, text in (("graph", gb), ("width", cw)):
    s1 = numbers(text, f"{'graph_break' if name == 'graph' else 'charwidth'}_stage1")
    s2 = numbers(text, f"{'graph_break' if name == 'graph' else 'charwidth'}_stage2")
    assert len(s2) % 128 == 0 and max(s1) * 128 < len(s2) and max(s2) < 36 and min(s2) >= 0
    lines += chunks(f"{name}_stage1", "".join(f"{v:02x}" for v in s1))
    lines += chunks(f"{name}_stage2", "".join(b36(v) for v in s2))
out.write_text("\n".join(lines), newline="\n")
print(out, len(gb), len(cw))
