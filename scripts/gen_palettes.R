# Writes lib/e/gfx/palettes_data.e: the discrete palettes of ggsci (every palette of every pal_*) and
# ggthemes (the *_pal functions with default arguments and the Tableau palettes) as one name|colours table.
.libPaths(c(Sys.getenv("R_ORACLE_LIB"), .libPaths()))
suppressMessages({ library(ggsci); library(ggthemes) })
rows <- character()
add <- function(name, cols) { cols <- toupper(substr(cols, 1, 7)); if (length(cols) && all(grepl("^#[0-9A-F]{6}$", cols))) rows[[length(rows) + 1]] <<- paste0(name, "|", paste(cols, collapse = ",")) }
for (fn in grep("^pal_", getNamespaceExports("ggsci"), value = TRUE)) {
  f <- get(fn, asNamespace("ggsci")); fm <- formals(f)
  if (!is.null(fm$n)) next
  pals <- if (!is.null(fm$palette)) eval(fm$palette) else NA
  for (p in pals) {
    pf <- tryCatch(if (is.na(p)) f() else f(palette = p), error = function(e) NULL)
    if (is.null(pf)) next
    mx <- attr(pf, "max_n"); if (is.null(mx)) mx <- 8
    cols <- tryCatch(pf(mx), error = function(e) NULL)
    if (!is.null(cols)) add(paste0("ggsci.", fn, if (is.na(p)) "" else paste0(":", p)), cols)
  }
}
tp <- ggthemes::ggthemes_data[["tableau"]][["color-palettes"]]
for (ty in names(tp)) for (nm in names(tp[[ty]])) add(paste0("tableau.", ty, ":", nm), tp[[ty]][[nm]][["value"]])
for (fn in c("economist_pal", "colorblind_pal", "fivethirtyeight_pal", "few_pal", "calc_pal", "excel_pal", "gdocs_pal", "hc_pal", "pander_pal", "solarized_pal", "stata_pal", "wsj_pal", "tableau_color_pal")) {
  f <- tryCatch(get(fn, asNamespace("ggthemes")), error = function(e) NULL)
  if (is.null(f)) next
  pf <- tryCatch(f(), error = function(e) NULL); if (is.null(pf)) next
  mx <- attr(pf, "max_n"); if (is.null(mx)) next
  add(paste0("ggthemes.", fn), pf(mx))
}
cat("ROWS", length(rows), "
")
writeLines(c("// generated by scripts/gen_palettes.R from ggsci and ggthemes: one palette per line, name|#RRGGBB,#RRGGBB,...", "", paste0("fn rows() -> str { ret \"", paste0(paste(rows, collapse = "\\n"), "\\n"), "\" }"), ""), "lib/e/gfx/palettes_data.e")
