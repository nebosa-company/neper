"""Bakes v3's toolbar bitmaps (the 16 x 16 pictures of the dxBar buttons, greyscale where disabled) into lib/e/ui/wintoolicon.e.
Cut from docs/ui/looks/ref/windows/toolbar_button_row.png (25 pictures, ids 0..24) and toolbar_button_hot.png (the two Cards
buttons that are enabled there, ids 25 and 26 for buttons 14 and 15). A pixel equal to the bar face under the picture is not painted;
every other pixel is kept as captured (the face is a flat #F0F0F0 there). Edit this script, not the generated file."""
from PIL import Image
L = 'docs/ui/looks/ref/windows/'
row = Image.open(L + 'toolbar_button_row.png').convert('RGB')
hot = Image.open(L + 'toolbar_button_hot.png').convert('RGB')
ORG = [26, 49, 78, 101, 130, 159, 182, 205, 242, 265, 288, 311, 340, 363, 392, 415, 438, 474, 497, 520, 543, 566, 589, 625, 648]
tiles = []
for o in ORG:
    tiles.append((row, o, 36))
sh = 654 - 384
for j in (14, 15):
    tiles.append((hot, ORG[j] + sh, 36))
vals = []
for im, x0, y0 in tiles:
    face = im.getpixel((x0 + 8, y0 + 18))
    for y in range(17):
        for x in range(16):
            p = im.getpixel((x0 + x, y0 + y))
            vals.append(0 if p == face else 0xFF000000 | p[0] << 16 | p[1] << 8 | p[2])
dx = ', '.join('%dusize' % (1 if i < 8 else 2) for i in range(len(tiles)))
body = ', '.join('0x%08Xu32' % v for v in vals)
n = len(vals)
open('lib/e/ui/wintoolicon.e', 'w', newline='\n').write(
    '// GENERATED by scripts/gen_wintoolicon.py from ref/windows/toolbar_button_row.png and toolbar_button_hot.png: v3\'s dxBar button\n'
    '// pictures, %d tiles of 16 x 17, 0xAARRGGBB, alpha 0 = the bar face. Edit the script, not this file.\n\n'
    'fn count() -> usize { ret %dusize }\n'
    '// columns the picture sits right of the button\'s 16 x 16 picture box\n'
    'fn dx(id: usize) -> usize { let d = [%d]usize{ %s }\n    ret d[id] }\n'
    'fn atlas() -> [%d]u32 { ret [%d]u32{ %s } }\n' % (len(tiles), len(tiles), len(tiles), dx, n, n, body))
