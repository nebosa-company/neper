#!/usr/bin/env python3
"""Generate lib/e/js/tzpack.e: every IANA zone of the installed `tzdata` package in the e.tz pack format, for Intl and Temporal.

Run after updating tzdata:  python scripts/gen_tzpack.py
The pack shape is the one tests/selfhost/fixtures/link/tz/reference.py documents (NPTZ, version, count, then name + TZif per zone).
"""
import importlib.resources as resources
import os
import struct
from pathlib import Path

import tzdata

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "lib" / "e" / "js" / "tzpack.e"
SKIP_TOP = {"posix", "right"}
SKIP_NAMES = {"leapseconds", "posixrules", "Factory", "localtime"}
CHUNK = 300


def zone_names(base: str):
    names = []
    for dirpath, _dirs, files in os.walk(base):
        for f in files:
            if "." in f:
                continue
            rel = os.path.relpath(os.path.join(dirpath, f), base).replace(chr(92), "/")
            if rel.split("/")[0] in SKIP_TOP or rel in SKIP_NAMES:
                continue
            names.append(rel)
    return sorted(names)


def literal(data: bytes) -> str:
    out = []
    for b in data:
        if b < 32 or b > 126 or b in (34, 92):
            out.append("\\x%02x" % b)
        else:
            out.append(chr(b))
    return '"' + "".join(out) + '"'


def main() -> None:
    root = resources.files("tzdata.zoneinfo")
    base = str(root)
    names = zone_names(base)
    version = tzdata.IANA_VERSION.encode()
    blob = b"NPTZ" + struct.pack("<H", len(version)) + version + struct.pack("<I", len(names))
    for name in names:
        data = (root / name).read_bytes()
        assert data[:4] == b"TZif", name
        blob += struct.pack("<H", len(name)) + name.encode() + struct.pack("<I", len(data)) + data
    pushes = []
    for i in range(0, len(blob), CHUNK):
        pushes.append("    try str.push(&b, " + literal(blob[i:i + CHUNK]) + ")")
    zi = resources.files("tzdata.zoneinfo").joinpath("tzdata.zi").read_text()
    link_lines = [l for l in zi.splitlines() if l.startswith("L ")]
    link_text = "".join(l[2:] + chr(10) for l in link_lines)
    link_pushes = []
    for i in range(0, len(link_text), 200):
        link_pushes.append("    try str.push(&b, " + literal(link_text[i:i + 200].encode()) + ")")
    OUT.write_text(
        "// Every zone of the IANA release below in the e.tz pack format, generated by scripts/gen_tzpack.py -- edit that, not this file.\n\n"
        "use e.mem\nuse e.str\n\n"
        f"fn pack(a: *mem.Arena) -> (str, err) {{\n    var b = try str.builder(a, {len(blob) + 64})\n"
        + "\n".join(pushes)
        + "\n    ret (str.done(&b), ok)\n}\n\n"
        + "// The IANA link names, one \"target alias\" per line.\n"
        + f"fn links(a: *mem.Arena) -> (str, err) {{\n    var b = try str.builder(a, {len(link_text) + 64})\n"
        + "\n".join(link_pushes)
        + "\n    ret (str.done(&b), ok)\n}\n",
        encoding="utf-8",
        newline="\n",
    )
    print(len(names), "zones", len(blob), "bytes", tzdata.IANA_VERSION)


main()
