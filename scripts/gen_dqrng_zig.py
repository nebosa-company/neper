import re
import sys
# usage: python scripts/gen_dqrng_zig.py <BH include dir>/boost/random/ > tables.e; the output replaces the Zig block of lib/e/algo/rand/dqrng.e
B = sys.argv[1]

def table(path, name):
    t = open(B + path, encoding='utf-8').read()
    m = re.search(name + r'<RealType>::(table_[xy])\[(\d+)\] = \{(.*?)\};', t, re.S)
    return None

def grab(path, struct):
    t = open(B + path, encoding='utf-8').read()
    out = {}
    for m in re.finditer(r'const RealType ' + struct + r'<RealType>::(table_[xy])\[(\d+)\] = \{(.*?)\};', t, re.S):
        vals = [v.strip() for v in m.group(3).replace('\n', ' ').split(',') if v.strip()]
        assert len(vals) == int(m.group(2)), (m.group(1), len(vals))
        out[m.group(1)] = vals
    return out

nt = grab('normal_distribution.hpp', 'normal_table')
et = grab('exponential_distribution.hpp', 'exponential_table')

def lit(v):
    if '.' not in v:
        v = v + '.0'
    return v + 'f64'

lines = []
lines.append('')
lines.append('// Boost.Random 1.8x ziggurat tables (normal_table, exponential_table) as dqrng uses them; generated by D:/Temp/gen_zig.py from the BH headers')
lines.append('type Zig = struct { nx: [129]f64, ny: [129]f64, ex: [257]f64, ey: [257]f64 }')
lines.append('')
lines.append('fn zig_init(z: *Zig) {')
for nm, tb in (('nx', nt['table_x']), ('ny', nt['table_y']), ('ex', et['table_x']), ('ey', et['table_y'])):
    for i, v in enumerate(tb):
        lines.append('    z.%s[%dusize] = %s' % (nm, i, lit(v)))
lines.append('}')
open('D:/Temp/zig_tables.e', 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print(len(lines))
