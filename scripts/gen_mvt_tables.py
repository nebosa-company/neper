# Writes lib/e/algo/stat/mvt_tables.e: the lattice rule parameters (P(1..28) and C(1..28, 1..99)) of mvtnorm's mvt.f (Genz, Bretz).
import re, sys
src = open(sys.argv[1], encoding='latin-1').read()
rows = []
for m in re.finditer(r'DATA\s+P\(\s*(\d+)\)\s*,\s*\(\s*C\(\s*\d+\s*,\s*I\)\s*,\s*I\s*=\s*1\s*,\s*99\)\s*/(.*?)/', src, re.S):
    body = re.sub(r'\n\s*&', ' ', m.group(2))
    vals = []
    for tok in body.replace('\n', ' ').split(','):
        tok = tok.strip()
        if not tok: continue
        if '*' in tok:
            n, v = tok.split('*'); vals += [int(v)] * int(n)
        else:
            vals.append(int(tok))
    assert len(vals) == 100, (m.group(1), len(vals))
    rows.append(vals)
assert len(rows) == 28
with open(sys.argv[2], 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by scripts/gen_mvt_tables.py from mvtnorm 1.4-2 mvt.f. Do not edit.\n')
    f.write('// lattice: 28 rows separated by |, the prime P(i) then C(i, 1..99), space separated.\n')
    f.write('fn lattice() -> str { ret "' + '|'.join(' '.join(map(str, r)) for r in rows) + '" }\n')
