#!/usr/bin/env python3
"""Generate lib/e/time/names.e (L150, D3601, D4605): month and weekday names (wide and abbreviated, format context), the
stand-alone month names where they differ, and the AM/PM marks of 27 languages and of the regional and script variants
whose names differ from their language's, from CLDR as shipped in Babel.

    PYTHONPATH=<Babel install dir> python scripts/gen_time_names.py
"""
import sys
from pathlib import Path

from babel import Locale, localedata
from babel.dates import get_period_names

sys.path.insert(0, str(Path(__file__).resolve().parent))
import fixture_common as fc  # noqa: E402

TAGS = ['en', 'fr', 'de', 'es', 'it', 'pt', 'nl', 'sv', 'da', 'nb', 'fi', 'pl', 'cs', 'hu', 'ro', 'ru', 'uk', 'tr',
        'el', 'ja', 'zh', 'ko', 'id', 'vi', 'ar', 'he', 'hi']
OUT = Path(__file__).resolve().parent.parent / 'lib' / 'e' / 'time' / 'names.e'


def data(loc):
    fm, fd, sm = loc.months['format'], loc.days['format'], loc.months['stand-alone']
    pn = get_period_names(width='abbreviated', context='format', locale=loc)
    fmt_w = ','.join(fm['wide'][i] for i in range(1, 13))
    fmt_a = ','.join(fm['abbreviated'][i] for i in range(1, 13))
    sa_w = ','.join(sm['wide'][i] for i in range(1, 13))
    sa_a = ','.join(sm['abbreviated'][i] for i in range(1, 13))
    return [fmt_w, fmt_a, ','.join(fd['wide'][i] for i in range(7)), ','.join(fd['abbreviated'][i] for i in range(7)),
            pn['am'], pn['pm'], '' if sa_w == fmt_w else sa_w, '' if sa_a == fmt_a else sa_a]


rows = []        # [tag] + data
aliases = {}     # normalized tag -> row index
for tag in TAGS:
    rows.append([tag] + data(Locale.parse(tag)))
base_of = {r[0]: r[1:] for r in rows}
for tag in TAGS:
    for ident in sorted(localedata.locale_identifiers()):
        if ident.split('_')[0] != tag or '_' not in ident:
            continue
        try:
            d = data(Locale.parse(ident))
        except Exception:
            continue
        if d == base_of[tag]:
            continue
        index = None
        for i, r in enumerate(rows):
            if i >= len(TAGS) and r[1:] == d:
                index = i
                break
        if index is None:
            rows.append([ident.replace('_', '-')] + d)
            index = len(rows) - 1
        aliases[ident.replace('_', '-').lower()] = index
for r in rows:
    for f in r:
        assert '|' not in f and '\n' not in f, (r[0], f)

fns = []
chain = []
for i, r in enumerate(rows):
    fns.append('fn row_%d() -> str {\n    ret "%s"\n}\n' % (i, fc.neper_str('|'.join(r))))
    chain.append('    if loc == %dusize { ret row_%d() }' % (i, i))
alias_chain = '\n'.join('    if str.eq(t, "%s") { ret (%dusize, true) }' % (k, v) for k, v in sorted(aliases.items()))

src = '''// Month and weekday names and the AM/PM marks of %(nbase)d languages and of %(nvar)d regional and script variants whose
// names differ from their language's (`pt-PT`, `en-GB`, `de-AT`, `zh-Hant`, ...), from CLDR (the format context, wide
// and abbreviated; the stand-alone month names where they differ), for `e.time.pattern`'s `format_locale` and
// `parse_locale`. A locale is an index into the table; `locale_index` finds the index of a BCP 47 tag
// (`fr`, `fr-CA` and `FR_ca` are written alike): the whole tag, then language-region, then language-script when
// the tag has a script, then the language. Index 0 is English. The rows are generated by `scripts/gen_time_names.py`.

use e.str

fn lower(b: u8) -> u8 {
    if b >= 65u8 && b <= 90u8 { ret b + 32u8 }
    ret b
}

fn locale_count() -> usize { ret %(nbase)dusize }

fn row_count() -> usize { ret %(nrows)dusize }

// The row `tag|months|abbreviated months|weekdays|abbreviated weekdays|am|pm|stand-alone months|stand-alone abbreviated
// months` of a locale (the last two empty when they are the format ones).
fn row(loc: usize) -> str {
%(chain)s
    ret ""
}

// The row of a lower-cased tag that names a regional or script variant.
fn alias(t: str) -> (usize, bool) {
%(alias_chain)s
    ret (0usize, false)
}

// The `n`th `|`-separated field of a row.
fn field(r: str, n: usize) -> str {
    var start = 0usize
    var seen = 0usize
    var i = 0usize
    while i <= r.len {
        if i == r.len || r[i] == 124u8 {
            if seen == n { ret r[start..i] }
            seen += 1usize
            start = i + 1usize
        }
        i += 1usize
    }
    ret ""
}

// The `n`th `,`-separated item of a field.
fn item(f: str, n: usize) -> str {
    var start = 0usize
    var seen = 0usize
    var i = 0usize
    while i <= f.len {
        if i == f.len || f[i] == 44u8 {
            if seen == n { ret f[start..i] }
            seen += 1usize
            start = i + 1usize
        }
        i += 1usize
    }
    ret ""
}

// The index of a language subtag (lower case), or false.
fn language_index(name: str) -> (usize, bool) {
    var loc = 0usize
    while loc < locale_count() {
        if str.eq(field(row(loc), 0usize), name) { ret (loc, true) }
        loc += 1usize
    }
    ret (0usize, false)
}

// The index of a tag: the whole tag as a variant, `language-region` and `language-script` of a tag with a script, then
// its language, case-insensitively, `_` and `-` alike. An unknown language is false.
fn locale_index(tag: str) -> (usize, bool) {
    var buf: [64]u8 = zero
    var n = 0usize
    while n < tag.len && n < 64usize {
        var c = lower(tag[n])
        if c == 95u8 { c = 45u8 }
        buf[n] = c
        n += 1usize
    }
    let whole: str = buf[0usize..n]
    var cut = 0usize
    while cut < n && buf[cut] != 45u8 { cut += 1usize }
    let language: str = buf[0usize..cut]
    let (lang_loc, lang_known) = language_index(language)
    if !lang_known { ret (0usize, false) }
    if cut == n { ret (lang_loc, true) }
    let (hit, found) = alias(whole)
    if found { ret (hit, true) }
    // subtags after the language: an optional four-letter script, an optional region of two letters or three digits
    var script_from = 0usize
    var script_to = 0usize
    var region_from = 0usize
    var region_to = 0usize
    var at = cut + 1usize
    var part = 0usize
    while at <= n && part < 3usize {
        var end = at
        while end < n && buf[end] != 45u8 { end += 1usize }
        let len = end - at
        if script_to == 0usize && region_to == 0usize && len == 4usize {
            script_from = at
            script_to = end
        } else if region_to == 0usize && (len == 2usize || (len == 3usize && buf[at] >= 48u8 && buf[at] <= 57u8)) {
            region_from = at
            region_to = end
        }
        at = end + 1usize
        part += 1usize
    }
    if region_to > 0usize {
        var key: [16]u8 = zero
        var k = 0usize
        while k < cut && k < 8usize {
            key[k] = buf[k]
            k += 1usize
        }
        key[k] = 45u8
        k += 1usize
        var r = region_from
        while r < region_to && k < 15usize {
            key[k] = buf[r]
            k += 1usize
            r += 1usize
        }
        let combined: str = key[0usize..k]
        let (rl, rf) = alias(combined)
        if rf { ret (rl, true) }
    }
    if script_to > 0usize {
        var key2: [16]u8 = zero
        var k2 = 0usize
        while k2 < cut && k2 < 8usize {
            key2[k2] = buf[k2]
            k2 += 1usize
        }
        key2[k2] = 45u8
        k2 += 1usize
        var r2 = script_from
        while r2 < script_to && k2 < 15usize {
            key2[k2] = buf[r2]
            k2 += 1usize
            r2 += 1usize
        }
        let scripted: str = key2[0usize..k2]
        let (sl, sf) = alias(scripted)
        if sf { ret (sl, true) }
    }
    ret (lang_loc, true)
}

// Month 1..12 in locale `loc`, wide or abbreviated (the format form, the one a date with a day uses).
fn month(loc: usize, m: u8, abbr: bool) -> str {
    if m < 1u8 || m > 12u8 { ret "" }
    var which = 1usize
    if abbr { which = 2usize }
    ret item(field(row(loc), which), usize(m) - 1usize)
}

// Month 1..12 in the stand-alone (nominative) form, which is the format one where the language has no other.
fn month_standalone(loc: usize, m: u8, abbr: bool) -> str {
    if m < 1u8 || m > 12u8 { ret "" }
    var which = 7usize
    if abbr { which = 8usize }
    let f = field(row(loc), which)
    if f.len == 0usize { ret month(loc, m, abbr) }
    ret item(f, usize(m) - 1usize)
}

// Weekday 0 (Monday) .. 6 (Sunday) in locale `loc`, wide or abbreviated.
fn weekday(loc: usize, index: i64, abbr: bool) -> str {
    if index < 0i64 || index > 6i64 { ret "" }
    var which = 3usize
    if abbr { which = 4usize }
    ret item(field(row(loc), which), usize(index))
}

// The AM or PM mark of locale `loc`.
fn day_period(loc: usize, pm: bool) -> str {
    var which = 5usize
    if pm { which = 6usize }
    ret field(row(loc), which)
}

%(fns)s''' % {'nbase': len(TAGS), 'nvar': len(rows) - len(TAGS), 'nrows': len(rows), 'chain': '\n'.join(chain),
              'alias_chain': alias_chain, 'fns': '\n'.join(fns)}
OUT.write_bytes(src.encode('utf-8'))
print('wrote', OUT, len(rows), 'rows', len(aliases), 'aliases')
