#!/usr/bin/env python3
"""Generate lib/e/time/names.e (L150, D3601): month and weekday names (wide and abbreviated, format context) and the
AM/PM marks of 27 locales, from CLDR as shipped in Babel.

    PYTHONPATH=<Babel install dir> python scripts/gen_time_names.py
"""
import sys
from pathlib import Path

from babel import Locale
from babel.dates import get_period_names

sys.path.insert(0, str(Path(__file__).resolve().parent))
import fixture_common as fc  # noqa: E402

TAGS = ['en', 'fr', 'de', 'es', 'it', 'pt', 'nl', 'sv', 'da', 'nb', 'fi', 'pl', 'cs', 'hu', 'ro', 'ru', 'uk', 'tr',
        'el', 'ja', 'zh', 'ko', 'id', 'vi', 'ar', 'he', 'hi']
OUT = Path(__file__).resolve().parent.parent / 'lib' / 'e' / 'time' / 'names.e'

rows = []
for tag in TAGS:
    loc = Locale.parse(tag)
    fmt_m, fmt_d = loc.months['format'], loc.days['format']
    fields = [tag,
              ','.join(fmt_m['wide'][i] for i in range(1, 13)),
              ','.join(fmt_m['abbreviated'][i] for i in range(1, 13)),
              ','.join(fmt_d['wide'][i] for i in range(7)),
              ','.join(fmt_d['abbreviated'][i] for i in range(7)),
              get_period_names(width='abbreviated', context='format', locale=loc)['am'],
              get_period_names(width='abbreviated', context='format', locale=loc)['pm']]
    for f in fields:
        assert '|' not in f and '\n' not in f, (tag, f)
    rows.append('|'.join(fields))

fns = []
chain = []
for i, row in enumerate(rows):
    fns.append('fn row_%d() -> str {\n    ret "%s"\n}\n' % (i, fc.neper_str(row)))
    chain.append('    if loc == %dusize { ret row_%d() }' % (i, i))

src = '''// Month and weekday names and the AM/PM marks of %d locales, from CLDR (the format context, wide
// and abbreviated), for `e.time.pattern`'s `format_locale` and `parse_locale`. A locale is an
// index into the table; `locale_index` finds the index of a BCP 47 tag by its language subtag
// (`fr`, `fr-CA` and `FR_ca` are all `fr`: regional variants are not distinguished). Index 0 is
// English. The rows are generated by `scripts/gen_time_names.py`.

fn lower(b: u8) -> u8 {
    if b >= 65u8 && b <= 90u8 { ret b + 32u8 }
    ret b
}

fn locale_count() -> usize { ret %dusize }

// The row `tag|months|abbreviated months|weekdays|abbreviated weekdays|am|pm` of a locale.
fn row(loc: usize) -> str {
%s
    ret ""
}

// The `n`th `|`-separated field of a row.
fn field(r: str, n: usize) -> str {
    var start = 0usize
    var seen = 0usize
    var i = 0usize
    while i <= r.len {
        if i == r.len || r[i] == 124u8 {
            if seen == n { ret r[start..i] }
            seen += 1usize
            start = i + 1usize
        }
        i += 1usize
    }
    ret ""
}

// The `n`th `,`-separated item of a field.
fn item(f: str, n: usize) -> str {
    var start = 0usize
    var seen = 0usize
    var i = 0usize
    while i <= f.len {
        if i == f.len || f[i] == 44u8 {
            if seen == n { ret f[start..i] }
            seen += 1usize
            start = i + 1usize
        }
        i += 1usize
    }
    ret ""
}

// The index of a tag's language subtag, case-insensitively.
fn locale_index(tag: str) -> (usize, bool) {
    var end = 0usize
    while end < tag.len && tag[end] != 45u8 && tag[end] != 95u8 { end += 1usize }
    var loc = 0usize
    while loc < locale_count() {
        let name = field(row(loc), 0usize)
        if name.len == end {
            var same = true
            var k = 0usize
            while k < end {
                if lower(tag[k]) != name[k] { same = false }
                k += 1usize
            }
            if same { ret (loc, true) }
        }
        loc += 1usize
    }
    ret (0usize, false)
}

// Month 1..12 in locale `loc`, wide or abbreviated.
fn month(loc: usize, m: u8, abbr: bool) -> str {
    if m < 1u8 || m > 12u8 { ret "" }
    var which = 1usize
    if abbr { which = 2usize }
    ret item(field(row(loc), which), usize(m) - 1usize)
}

// Weekday 0 (Monday) .. 6 (Sunday) in locale `loc`, wide or abbreviated.
fn weekday(loc: usize, index: i64, abbr: bool) -> str {
    if index < 0i64 || index > 6i64 { ret "" }
    var which = 3usize
    if abbr { which = 4usize }
    ret item(field(row(loc), which), usize(index))
}

// The AM or PM mark of locale `loc`.
fn day_period(loc: usize, pm: bool) -> str {
    var which = 5usize
    if pm { which = 6usize }
    ret field(row(loc), which)
}

''' % (len(TAGS), len(TAGS), '\n'.join(chain)) + '\n'.join(fns)
OUT.write_bytes(src.encode('utf-8'))
print('wrote', OUT, len(TAGS), 'locales')
