// Generates lib/e/text/uprops.e: the Unicode property tables behind RegExp \p{...} (general categories, scripts, script
// extensions and the binary properties of ECMA-262). The code point sets come from the Unicode data inside this node
// (process.versions.unicode); the *names* a property may be written with (long and short aliases) are read from the file
// names and `\p{...}` spellings of test262's generated property-escape tests, whose directory is the argument:
//
//   node scripts/gen_uprops.mjs D:/Temp/test262/test/built-ins/RegExp/property-escapes/generated
//
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = process.argv[2];
if (!dir) throw new Error('usage: node scripts/gen_uprops.mjs <test262 property-escapes/generated directory>');
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'lib', 'e', 'text', 'uprops.e');

// Every scalar value and lone surrogate, as one string, with the index of each code point's first unit.
const all = [];
for (let c = 0; c <= 0x10FFFF; c++) all.push(String.fromCodePoint(c));
const text = all.join('');
const starts = new Int32Array(0x110000 + 1);
{ let u = 0; for (let c = 0; c <= 0x10FFFF; c++) { starts[c] = u; u += c > 0xFFFF ? 2 : 1; } starts[0x110000] = u; }
const unitToCp = new Map();
function cpAtUnit(u) {
  // binary search over starts
  let lo = 0, hi = 0x110000;
  while (lo < hi) { const mid = (lo + hi + 1) >> 1; if (starts[mid] <= u) lo = mid; else hi = mid - 1; }
  return lo;
}

function rangesOf(expression) {
  const re = new RegExp('\\p{' + expression + '}+', 'gu');
  const ranges = [];
  for (const m of text.matchAll(re)) {
    const lo = cpAtUnit(m.index);
    const hi = cpAtUnit(m.index + m[0].length - 1);
    ranges.push([lo, hi]);
  }
  return ranges;
}

const tables = [];       // { expression, ranges }
const names = new Map(); // spelled name -> table index
for (const f of readdirSync(dir)) {
  if (!f.endsWith('.js')) continue;
  const base = f.slice(0, -3);
  let expression = base;
  const m = /^(Script_Extensions|Script|General_Category)_-_(.+)$/.exec(base);
  if (m) expression = m[1] + '=' + m[2];
  const spelled = new Set();
  for (const hit of readFileSync(join(dir, f), 'utf8').matchAll(/\\p\{([^}]+)\}/g)) spelled.add(hit[1]);
  const ranges = rangesOf(expression);
  const id = tables.length;
  tables.push({ expression, ranges });
  for (const n of spelled) names.set(n, id);
}

function esc(bytes) {
  let s = '';
  for (const b of bytes) {
    if (b === 0x22) s += '\\"';
    else if (b === 0x5c) s += '\\\\';
    else if (b >= 0x20 && b < 0x7f) s += String.fromCharCode(b);
    else s += '\\x' + b.toString(16).padStart(2, '0');
  }
  return s;
}

let src = '// Unicode property tables for RegExp \\p{...}, generated by scripts/gen_uprops.mjs -- edit the generator, not this file.\n';
src += '// Unicode ' + process.versions.unicode + '. A table is its ranges as 3-byte little-endian (start, end) pairs, sorted.\n\n';
src += 'use e.str\n\n';
tables.forEach((t, i) => {
  const bytes = [];
  for (const [lo, hi] of t.ranges) bytes.push(lo & 255, (lo >> 8) & 255, (lo >> 16) & 255, hi & 255, (hi >> 8) & 255, (hi >> 16) & 255);
  src += 'fn t' + i + '() -> str { ret "' + esc(bytes) + '" }\n';
});
src += '\nfn table(id: u32) -> str {\n';
function tree(lo, hi, indent) {
  if (hi - lo <= 4) {
    let r = '';
    for (let i = lo; i < hi; i++) r += indent + 'if id == ' + i + 'u32 { ret t' + i + '() }\n';
    return r;
  }
  const mid = (lo + hi) >> 1;
  return indent + 'if id < ' + mid + 'u32 {\n' + tree(lo, mid, indent + '    ') + indent + '} else {\n' + tree(mid, hi, indent + '    ') + indent + '}\n';
}
src += tree(0, tables.length, '    ');
src += '    ret ""\n}\n\n';
// name -> table: "name=id," entries
const index = [...names.entries()].map(([n, id]) => n + '=' + id).join(',') + ',';
src += 'fn index() -> str { ret "' + esc(Buffer.from(index)) + '" }\n\n';
src += `// The table named by a \\p{...} spelling (Lu, gc=Lu, Script=Latn, ASCII_Hex_Digit, ...), if there is one.
fn find(name: str) -> (u32, bool) {
    let idx = index()
    var start = 0usize
    var i = 0usize
    while i < idx.len {
        if idx[i] == 44u8 {
            let entry = idx[start..i]
            var eq = entry.len
            while eq > 0usize && entry[eq - 1usize] != 61u8 { eq -= 1usize }
            if eq > 0usize && str.eq(entry[0usize..eq - 1usize], name) {
                var id = 0u32
                var k = eq
                while k < entry.len {
                    id = id * 10u32 + u32(entry[k] - 48u8)
                    k += 1usize
                }
                ret (id, true)
            }
            start = i + 1usize
        }
        i += 1usize
    }
    ret (0u32, false)
}

fn read3(t: str, at: usize) -> u32 {
    ret u32(t[at]) | (u32(t[at + 1usize]) << 8u32) | (u32(t[at + 2usize]) << 16u32)
}

// Whether code point \`c\` is in table \`id\`.
fn contains(id: u32, c: u32) -> bool {
    let t = table(id)
    var low = 0usize
    var high = t.len / 6usize
    while low < high {
        let mid = (low + high) / 2usize
        let lo = read3(t, mid * 6usize)
        let hi = read3(t, mid * 6usize + 3usize)
        if c < lo { high = mid } else if c > hi { low = mid + 1usize } else { ret true }
    }
    ret false
}
`;
writeFileSync(out, src);
console.log('wrote', out, tables.length, 'tables,', names.size, 'names,', src.length, 'bytes');
