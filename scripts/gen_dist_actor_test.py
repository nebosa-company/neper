"""Generates the vector region of tests/selfhost/fixtures/link/dist_actor (L141, D2764).

Oracles: the `xxhash` package (xxh64, seed 0) for the placement keys and silo ids, and an
independent Python statement of rendezvous hashing for which silo a grain lands on, before and
after a silo is removed (checking the property that only the removed silo's grains move); and
the reminder schedule arithmetic written as `due + k * period`, the smallest k >= 1 that is
after `now`.

    PYTHONPATH=<dir with xxhash> python scripts/gen_dist_actor_test.py
"""
import sys
from pathlib import Path

import xxhash

FIXTURE = Path(__file__).resolve().parent.parent / 'tests/selfhost/fixtures/link/dist_actor/src/main.e'
M = (1 << 64) - 1
SILOS = ['silo-a', 'silo-b', 'silo-c', 'silo-d']
GRAINS = ['grain-%d' % i for i in range(16)]


def mix(x):
    v = x ^ (x >> 33)
    v = (v * 18397679294719823053) & M
    v ^= v >> 33
    v = (v * 14181476777654086739) & M
    return v ^ (v >> 33)


def rendezvous(nodes, key):
    best = 0
    bw = 0
    for i, n in enumerate(nodes):
        w = mix(n ^ mix(key))
        if i == 0 or w > bw or (w == bw and n < nodes[best]):
            best, bw = i, w
    return best


def place(alive):
    ids = [xxhash.xxh64(SILOS[i].encode()).intdigest() for i in alive]
    out = {}
    for g in GRAINS:
        out[g] = alive[rendezvous(ids, xxhash.xxh64(g.encode()).intdigest())]
    return out


def next_due(due, period, now):
    k = (now - due) // period + 1
    if k < 1:
        k = 1
    return due + k * period


def main():
    before = place([0, 1, 2, 3])
    after = place([0, 2, 3])
    for g in GRAINS:
        if before[g] != 1:
            assert after[g] == before[g], 'rendezvous moved a grain it should not have'
    out = []
    out.append('fn gen_before(k: usize) -> usize {')
    for i, g in enumerate(GRAINS):
        out.append('    if k == %dusize { ret %dusize }' % (i, before[g]))
    out.append('    ret 99usize')
    out.append('}')
    out.append('fn gen_after(k: usize) -> usize {')
    for i, g in enumerate(GRAINS):
        out.append('    if k == %dusize { ret %dusize }' % (i, after[g]))
    out.append('    ret 99usize')
    out.append('}')
    out.append('fn gen_on_silo1() -> usize { ret %dusize }' % sum(1 for g in GRAINS if before[g] == 1))
    cases = [(1500, 1000, 1500), (1500, 1000, 2499), (1500, 1000, 2500), (1500, 1000, 5000), (100, 100, 1450),
             (100, 100, 100), (0, 7, 100), (1000, 250, 999)]
    out.append('fn gen_next_due(k: usize) -> i64 {')
    for i, (d, p, n) in enumerate(cases):
        out.append('    if k == %dusize { ret %di64 }' % (i, next_due(d, p, n)))
    out.append('    ret 0i64')
    out.append('}')
    out.append('fn gen_due_in(k: usize) -> i64 {')
    for i, (d, p, n) in enumerate(cases):
        out.append('    if k == %dusize { ret %di64 }' % (i, d))
    out.append('    ret 0i64')
    out.append('}')
    out.append('fn gen_period_in(k: usize) -> i64 {')
    for i, (d, p, n) in enumerate(cases):
        out.append('    if k == %dusize { ret %di64 }' % (i, p))
    out.append('    ret 0i64')
    out.append('}')
    out.append('fn gen_now_in(k: usize) -> i64 {')
    for i, (d, p, n) in enumerate(cases):
        out.append('    if k == %dusize { ret %di64 }' % (i, n))
    out.append('    ret 0i64')
    out.append('}')
    out.append('fn gen_cases() -> usize { ret %dusize }' % len(cases))
    text = FIXTURE.read_text(encoding='utf-8')
    b = text.index('// BEGIN generated')
    e = text.index('// END generated')
    text = text[:b] + '// BEGIN generated by scripts/gen_dist_actor_test.py\n' + '\n'.join(out) + '\n' + text[e:]
    FIXTURE.write_bytes(text.encode('utf-8'))
    print('on silo 1:', sum(1 for g in GRAINS if before[g] == 1), 'of', len(GRAINS))


if __name__ == '__main__':
    sys.exit(main())
