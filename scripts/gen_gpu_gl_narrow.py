HEADER = r'''// f16 and bf16 on e.gpu's `.Gl` backend (C216, D5914), built with `--gpu glsl`: each kernel runs on the CPU backend
// (D5913: widen to f32, operate, round once) and on the GL device, and every output word must be equal. 4096 operand sets from
// a fixed stream, with zeros, denormals, infinities, NaNs and ties over-represented: + - * /, square root, negation, fused
// multiply-add, the six comparisons, widening to f32, f16 <-> bf16, f32 to narrow (ties and denormals included) and 32-bit
// integers to narrow. A device that keeps f32 denormals runs the plain kernel and one that flushes them the `ftz` one; the
// answers are the same, since a widened narrow value is never an f32 denormal. Generated by scripts/gen_gpu_gl_narrow.py; do
// not edit. A host without an OpenGL device says so and passes.

use e.gpu
use e.io
use e.math
use e.mem
use e.os
use x.khronos.compute

const N: usize = 4096usize

fn next(s: *u64) -> u64 {
    *s = *s *% 6364136223846793005u64 +% 1442695040888963407u64
    ret *s
}

fn pick_h(s: *u64) -> u16 {
    let r = next(s)
    let k = (r >> 33u64) % 6u64
    let v = u16(r >> 48u64)
    let sign = v & 32768u16
    if k == 0u64 {
        if (r >> 20u64) % 2u64 == 0u64 { ret sign | 31744u16 }
        ret sign | 31744u16 | (v & 1023u16)
    }
    if k == 1u64 { ret v & 33791u16 }
    if k == 2u64 { ret (v & 33791u16) | u16((13u64 + (r >> 8u64) % 5u64) << 10u64) }
    ret v
}

fn pick_b(s: *u64) -> u16 {
    let r = next(s)
    let k = (r >> 33u64) % 6u64
    let v = u16(r >> 48u64)
    let sign = v & 32768u16
    if k == 0u64 {
        if (r >> 20u64) % 2u64 == 0u64 { ret sign | 32640u16 }
        ret sign | 32640u16 | (v & 127u16)
    }
    if k == 1u64 { ret v & 32895u16 }
    if k == 2u64 { ret (v & 32895u16) | u16((125u64 + (r >> 8u64) % 5u64) << 7u64) }
    ret v
}

// f32 bit patterns: any, and exponents where the narrow type rounds, with the rounding tie and its neighbours.
fn pick_f32(s: *u64, bf: bool) -> u32 {
    let r = next(s)
    let k = (r >> 40u64) % 8u64
    let v = u32((r >> 16u64) & 4294967295u64)
    if k == 0u64 { ret v }
    if k == 1u64 { ret (v & 2155872255u32) | 2139095040u32 }
    var exponent = 100u32 + u32((r >> 8u64) % 60u64)
    if bf { exponent = 1u32 + u32((r >> 8u64) % 250u64) }
    var mantissa = v & 8388607u32
    var keep = 8384512u32
    var tie = 4096u32
    if bf {
        keep = 8323072u32
        tie = 32768u32
    }
    if k == 2u64 { mantissa = (mantissa & keep) | tie }
    if k == 3u64 { mantissa = (mantissa & keep) | (tie - 1u32) }
    if k == 4u64 { mantissa = (mantissa & keep) | (tie + 1u32) }
    ret (v & 2147483648u32) | (exponent << 23u32) | mantissa
}

fn pick_i32(s: *u64) -> i32 {
    let r = next(s)
    let bits = 1u64 + (r >> 50u64) % 31u64
    var v = u32((r >> 8u64) & 4294967295u64)
    v = v & ((1u32 << u32(bits)) - 1u32)
    if (r >> 4u64) % 2u64 == 0u64 { ret i32(v) }
    ret 0i32 - i32(v)
}

// f64 bit patterns: any, specials, and exponents where the narrow type rounds with its tie and neighbours.
fn pick_f64(s: *u64, bf: bool) -> u64 {
    let r = next(s)
    let k = (r >> 40u64) % 8u64
    let v = next(s)
    if k == 0u64 { ret v }
    if k == 1u64 { ret (v & 9227875636482146303u64) | 9218868437227405312u64 }
    var exponent = 1023u64 - 30u64 + (r >> 8u64) % 60u64
    if bf { exponent = 1023u64 - 140u64 + (r >> 8u64) % 280u64 }
    if bf && exponent > 2046u64 { exponent = 2046u64 }
    var mantissa = v & 4503599627370495u64
    var keep = 18446744073709551615u64 << 42u64
    var tie = 2199023255552u64
    if bf {
        keep = 18446744073709551615u64 << 45u64
        tie = 17592186044416u64
    }
    keep = keep & 4503599627370495u64
    if k == 2u64 { mantissa = (mantissa & keep) | tie }
    if k == 3u64 { mantissa = (mantissa & keep) | (tie - 1u64) }
    if k == 4u64 { mantissa = (mantissa & keep) | (tie + 1u64) }
    ret (v & 9223372036854775808u64) | (exponent << 52u64) | mantissa
}

fn bits_f32(value: u32) -> f32 {
    var held = value
    ret *mem.cast[*f32](&held)
}

fn bits_of(p: *u16) -> u32 { ret u32(*p) }

fn same_outputs(tag: str, cpu: []const u32, gl: []const u32) {
    var at = 0usize
    while at < cpu.len {
        if cpu[at] != gl[at] {
            let stream = at / N
            let element = at % N
            let printed = io.printf["{} stream {} element {}: cpu {} gl {}\n"](tag, stream, element, cpu[at], gl[at])
            os.exit(10i32 + i32(stream))
        }
        at += 1usize
    }
}
'''

PER_TYPE = r'''
@gpu(64@ATTR@)
fn ops_@TAG@@SUF@(n: u32, x: []const @T@, y: []const @T@, z: []const @T@, xf: []const f32, xi: []const i32, o: []@T@, c: []u32, w: []f32, ot: []@OT@, fh: []@T@, ih: []@T@, uh: []@T@) {
    let i = gpu.gid.x
    if i >= n { ret }
    let k = usize(i)
    let a = x[k]
    let b = y[k]
    let base = k * 7usize
    o[base] = a + b
    o[base + 1usize] = a - b
    o[base + 2usize] = a * b
    o[base + 3usize] = a / b
    o[base + 4usize] = math.sqrt[@T@](a)
    o[base + 5usize] = -a
    o[base + 6usize] = math.fma[@T@](a, b, z[k])
    var m = 0u32
    if a < b { m = m | 1u32 }
    if a <= b { m = m | 2u32 }
    if a > b { m = m | 4u32 }
    if a >= b { m = m | 8u32 }
    if a == b { m = m | 16u32 }
    if a != b { m = m | 32u32 }
    c[k] = m
    w[k] = f32(a)
    ot[k] = @OT@(a)
    fh[k] = @T@(xf[k])
    ih[k] = @T@(xi[k])
    uh[k] = @T@(u32(xi[k] & 2147483647i32))
}
'''

RUN = r'''
fn run_@TAG@(a: *mem.Arena, backend: gpu.Backend, flushing: bool, x: []const @T@, y: []const @T@, z: []const @T@, xf: []const f32, xi: []const i32, out: []u32) -> err {
    let (device, open_error) = gpu.open(a, backend, 0u32)
    if open_error != ok { ret open_error }
    let (queue, queue_error) = gpu.queue(device)
    if queue_error != ok { ret queue_error }
    let (dx, dx_error) = gpu.upload[@T@](queue, x)
    let (dy, dy_error) = gpu.upload[@T@](queue, y)
    let (dz, dz_error) = gpu.upload[@T@](queue, z)
    let (dxf, dxf_error) = gpu.upload[f32](queue, xf)
    let (dxi, dxi_error) = gpu.upload[i32](queue, xi)
    let (o, o_error) = gpu.alloc[@T@](queue, 7usize * N)
    let (c, c_error) = gpu.alloc[u32](queue, N)
    let (w, w_error) = gpu.alloc[f32](queue, N)
    let (ot, ot_error) = gpu.alloc[@OT@](queue, N)
    let (fh, fh_error) = gpu.alloc[@T@](queue, N)
    let (ih, ih_error) = gpu.alloc[@T@](queue, N)
    let (uh, uh_error) = gpu.alloc[@T@](queue, N)
    if dx_error != ok || dy_error != ok || dz_error != ok || dxf_error != ok || dxi_error != ok { os.exit(2i32) }
    if o_error != ok || c_error != ok || w_error != ok || ot_error != ok || fh_error != ok || ih_error != ok || uh_error != ok { os.exit(3i32) }
    var launched = ok
    if flushing { launched = gpu.launch[ops_@TAG@_ftz](queue, gpu.grid1(N), u32(N), dx, dy, dz, dxf, dxi, o, c, w, ot, fh, ih, uh) } else { launched = gpu.launch[ops_@TAG@](queue, gpu.grid1(N), u32(N), dx, dy, dz, dxf, dxi, o, c, w, ot, fh, ih, uh) }
    if launched != ok { ret launched }
    let (ro, ro_error) = mem.alloc[@T@](a, 7usize * N)
    let (rc, rc_error) = mem.alloc[u32](a, N)
    let (rw, rw_error) = mem.alloc[f32](a, N)
    let (rot, rot_error) = mem.alloc[@OT@](a, N)
    let (rfh, rfh_error) = mem.alloc[@T@](a, N)
    let (rih, rih_error) = mem.alloc[@T@](a, N)
    let (ruh, ruh_error) = mem.alloc[@T@](a, N)
    if ro_error != ok || rc_error != ok || rw_error != ok || rot_error != ok || rfh_error != ok || rih_error != ok || ruh_error != ok { os.exit(4i32) }
    if gpu.download(queue, o, ro) != ok || gpu.download(queue, c, rc) != ok || gpu.download(queue, w, rw) != ok { os.exit(5i32) }
    if gpu.download(queue, ot, rot) != ok || gpu.download(queue, fh, rfh) != ok || gpu.download(queue, ih, rih) != ok || gpu.download(queue, uh, ruh) != ok { os.exit(6i32) }
    var at = 0usize
    while at < 7usize * N {
        out[at] = bits_of(mem.cast[*u16](&ro[at]))
        at += 1usize
    }
    at = 0usize
    while at < N {
        out[7usize * N + at] = rc[at]
        out[8usize * N + at] = *mem.cast[*u32](&rw[at])
        out[9usize * N + at] = bits_of(mem.cast[*u16](&rot[at]))
        out[10usize * N + at] = bits_of(mem.cast[*u16](&rfh[at]))
        out[11usize * N + at] = bits_of(mem.cast[*u16](&rih[at]))
        out[12usize * N + at] = bits_of(mem.cast[*u16](&ruh[at]))
        at += 1usize
    }
    ret gpu.close(device)
}

fn check_@TAG@(a: *mem.Arena, flushing: bool, seed: u64) -> err {
    let (x, x_error) = mem.alloc[@T@](a, N)
    let (y, y_error) = mem.alloc[@T@](a, N)
    let (z, z_error) = mem.alloc[@T@](a, N)
    let (xf, xf_error) = mem.alloc[f32](a, N)
    let (xi, xi_error) = mem.alloc[i32](a, N)
    let (cpu, cpu_error) = mem.alloc[u32](a, 13usize * N)
    let (gl, gl_error) = mem.alloc[u32](a, 13usize * N)
    if x_error != ok || y_error != ok || z_error != ok || xf_error != ok || xi_error != ok || cpu_error != ok || gl_error != ok { os.exit(7i32) }
    var s = seed
    var k = 0usize
    while k < N {
        *mem.cast[*u16](&x[k]) = pick_@PICK@(&s)
        *mem.cast[*u16](&y[k]) = pick_@PICK@(&s)
        *mem.cast[*u16](&z[k]) = pick_@PICK@(&s)
        xf[k] = bits_f32(pick_f32(&s, @BF@))
        xi[k] = pick_i32(&s)
        k += 1usize
    }
    if run_@TAG@(a, .Cpu, flushing, x, y, z, xf, xi, cpu) != ok { os.exit(8i32) }
    let gl_run = run_@TAG@(a, .Gl, flushing, x, y, z, xf, xi, gl)
    if gl_run != ok {
        let printed = io.printf["@TAG@: the GL launch answered {}\n"](gl_run)
        os.exit(9i32)
    }
    same_outputs("@TAG@", cpu, gl)
    ret ok
}
'''

PER64 = r'''
@gpu(64)
fn conv64_@TAG@(n: u32, xd: []const f64, x: []const @T@, fd: []@T@, wd: []f64) {
    let i = gpu.gid.x
    if i >= n { ret }
    let k = usize(i)
    fd[k] = @T@(xd[k])
    wd[k] = f64(x[k])
}

fn run64_@TAG@(a: *mem.Arena, backend: gpu.Backend, xd: []const f64, x: []const @T@, out: []u32) -> err {
    let (device, open_error) = gpu.open(a, backend, 0u32)
    if open_error != ok { ret open_error }
    let (queue, queue_error) = gpu.queue(device)
    if queue_error != ok { ret queue_error }
    let (dxd, dxd_error) = gpu.upload[f64](queue, xd)
    let (dx, dx_error) = gpu.upload[@T@](queue, x)
    let (fd, fd_error) = gpu.alloc[@T@](queue, N)
    let (wd, wd_error) = gpu.alloc[f64](queue, N)
    if dxd_error != ok || dx_error != ok || fd_error != ok || wd_error != ok { os.exit(2i32) }
    let launched = gpu.launch[conv64_@TAG@](queue, gpu.grid1(N), u32(N), dxd, dx, fd, wd)
    if launched != ok { ret launched }
    let (rfd, rfd_error) = mem.alloc[@T@](a, N)
    let (rwd, rwd_error) = mem.alloc[f64](a, N)
    if rfd_error != ok || rwd_error != ok { os.exit(4i32) }
    if gpu.download(queue, fd, rfd) != ok || gpu.download(queue, wd, rwd) != ok { os.exit(5i32) }
    var at = 0usize
    while at < N {
        out[at] = bits_of(mem.cast[*u16](&rfd[at]))
        let word = mem.bitcast[u64](rwd[at])
        out[N + at] = u32(word & 4294967295u64)
        out[2usize * N + at] = u32(word >> 32u64)
        at += 1usize
    }
    ret gpu.close(device)
}

fn check64_@TAG@(a: *mem.Arena, seed: u64) -> err {
    let (xd, xd_error) = mem.alloc[f64](a, N)
    let (x, x_error) = mem.alloc[@T@](a, N)
    let (cpu, cpu_error) = mem.alloc[u32](a, 3usize * N)
    let (gl, gl_error) = mem.alloc[u32](a, 3usize * N)
    if xd_error != ok || x_error != ok || cpu_error != ok || gl_error != ok { os.exit(7i32) }
    var s = seed
    var k = 0usize
    while k < N {
        *mem.cast[*u64](&xd[k]) = pick_f64(&s, @BF@)
        *mem.cast[*u16](&x[k]) = pick_@PICK@(&s)
        k += 1usize
    }
    if run64_@TAG@(a, .Cpu, xd, x, cpu) != ok { os.exit(8i32) }
    let gl_run = run64_@TAG@(a, .Gl, xd, x, gl)
    if gl_run != ok {
        let printed = io.printf["@TAG@ f64: the GL launch answered {}\n"](gl_run)
        os.exit(9i32)
    }
    same_outputs("@TAG@ f64", cpu, gl)
    ret ok
}
'''

MAIN_FN = r'''
fn main(a: *mem.Arena, args: []str) -> err {
    compute.install()
    let (found, found_error) = gpu.devices(a, .Gl, 4usize)
    if found_error != ok || found.len == 0usize {
        try io.print("no OpenGL compute device; nothing checked\n")
        ret ok
    }
    var flushing = true
    var narrow_ok = false
    var wide = false
    for capability in found[0usize].capabilities {
        if capability == .DenormPreserve { flushing = false }
        if capability == .Float16 { narrow_ok = true }
        if capability == .Float64 { wide = true }
    }
    if !narrow_ok {
        try io.print("no Float16 on this OpenGL device; nothing checked\n")
        ret ok
    }
    try check_h(a, flushing, 20261027u64)
    try check_b(a, flushing, 20261028u64)
    if wide && !flushing {
        try check64_h(a, 20261029u64)
        try check64_b(a, 20261030u64)
        try io.print("(f64 conversions too) ")
    }
    if flushing { try io.print("(ftz) ") }
    try io.print("f16 and bf16: 13 streams of 4096 words equal to the CPU backend's on ")
    try io.print(found[0usize].name)
    try io.print("\n")
    ret ok
}
'''


def fill(text, tag, t, other, pick, bf, attr='', suf=''):
    for key, value in (('TAG', tag), ('T', t), ('OT', other), ('PICK', pick), ('BF', bf), ('ATTR', attr), ('SUF', suf)):
        text = text.replace('@' + key + '@', value)
    return text


def build():
    out = HEADER
    for tag, t, other, pick, bf in (('h', 'f16', 'bf16', 'h', 'false'), ('b', 'bf16', 'f16', 'b', 'true')):
        for attr, suf in ((', ftz', '_ftz'), ('', '')):
            out += fill(PER_TYPE, tag, t, other, pick, bf, attr, suf)
        out += fill(RUN, tag, t, other, pick, bf)
    for tag, t, other, pick, bf in (('h', 'f16', 'bf16', 'h', 'false'), ('b', 'bf16', 'f16', 'b', 'true')):
        out += fill(PER64, tag, t, other, pick, bf)
    out += MAIN_FN
    return out


