#!/usr/bin/env python3
"""Write docs/appkit-api.md: the NeperOS app kit's API, level 1 (C173).

The kit is what a generated app may use: appkit, ui, text, theme, scenes, icons and the e.* library except the
system's own modules (neperos/src/scan.e keeps the same lists, and its strict scan refuses the rest). The function
list is read from the sources, so the document cannot drift from them; run this script after changing the kit.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
KIT = ["appkit", "ui", "text", "theme", "scenes", "icons"]


def signatures(path):
    out = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("fn "):
            out.append(line.rstrip(" {").strip())
    return out


def lists_from_scan():
    source = (ROOT / "neperos" / "src" / "scan.e").read_text(encoding="utf-8")
    system = re.findall(r'same_name\(name, "(e\.[a-z]+)"\)', source)
    banned = re.findall(r'ret "(os\.[a-z_0-9]+)"', source)
    level = re.search(r"const KIT_LEVEL: usize = (\d+)usize", source).group(1)
    return system, banned, level


def main():
    system, banned, level = lists_from_scan()
    lines = [
        "# The NeperOS app kit, level %s" % level,
        "",
        "Generated by `scripts/render_appkit_api.py` from `neperos/src`; do not edit.",
        "",
        "A generated app (a package a server builds from a prompt, `neperos/src/package.e`) is written against this API",
        "and nothing else. A package's `api` is the level it needs; a device that provides a lower one refuses it",
        "(`package.TooNew`). The server prefixes the model's prompt with this file and the card of traps in",
        "`docs/llm-neper-card.md`, and hands the compiler's diagnostics back as code, place, expected and found",
        "(the build server's loop in `tests/selfhost/fixtures/neperos/net/dynamic_services.py`).",
        "",
        "## What the scanner allows",
        "",
        "`neperos/src/scan.e` (`strict`, with `report` for the Details screen) finds, line by line:",
        "",
        "- raw machine access: %s;" % ", ".join("`%s`" % b for b in banned),
        "- a module outside the kit: the kit modules below and the `e.*` library, except %s;" % ", ".join("`%s`" % s for s in system),
        "- network or storage modules (`netclient`, `httpc`, `net_real`, `e.net`; `vaultfs`, `fsproto`, `fs`, `e.fs`) the",
        "  manifest's `capabilities` does not declare;",
        "- a `while true` whose body has no `break` and no `ret`.",
        "",
        "## Modules",
        "",
    ]
    for module in KIT:
        path = ROOT / "neperos" / "src" / (module + ".e")
        if not path.exists():
            continue
        lines.append("### `%s`" % module)
        lines.append("")
        lines.append("```")
        lines.extend(signatures(path))
        lines.append("```")
        lines.append("")
    dest = ROOT / "docs" / "appkit-api.md"
    dest.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("wrote", dest)
    return 0


sys.exit(main())
