"""Bakes v3's in-cell editor buttons into lib/e/ui/winedpic.e from ref/windows-1to1/data_grid_bottom.png (the current row, selection fill #A6D2FF):
the spin editor's left and right step buttons (8 x 15) and the button editor's three-dots button (15 x 14) and the hot Favorite header (23 x 22, data_grid_hover3), 0xAARRGGBB, alpha 0 where the pixel is the fill.
Edit this script, not the generated file. Run from the repository root with python -I."""
from PIL import Image
import numpy as np

r = np.array(Image.open('docs/ui/looks/ref/windows-1to1/data_grid_bottom.png').convert('RGB')).astype(int)
BG = (166, 210, 255)


def tile(x, y, w, h):
    out = []
    for yy in range(y, y + h):
        for xx in range(x, x + w):
            p = tuple(r[yy, xx])
            out.append(0 if p == BG else 0xFF000000 | (p[0] << 16) | (p[1] << 8) | p[2])
    return out


def emit(name, w, h, px):
    return 'fn %s_w() -> usize { ret %dusize }\nfn %s_h() -> usize { ret %dusize }\nfn %s() -> [%d]u32 { ret [%d]u32{ %s } }\n' % (
        name, w, name, h, name, w * h, w * h, ', '.join('0x%08Xu32' % v for v in px))


src = '// Generated by scripts/gen_winedpic.py from ref/windows-1to1/data_grid_bottom.png; edit the script.\n\n'
src += emit('spin_left', 8, 15, tile(267, 91, 8, 15))
src += emit('spin_right', 8, 15, tile(306, 91, 8, 15))
src += emit('dots', 15, 14, tile(413, 92, 15, 14))
# the hot Favorite header (ref/windows-1to1/data_grid_hover3.png, x 611 to 633, y 33 to 54): star and filter button on the hot fill, opaque
h = np.array(Image.open('docs/ui/looks/ref/windows-1to1/data_grid_hover3.png').convert('RGB')).astype(int)
fav = []
for yy in range(33, 55):
    for xx in range(611, 634):
        p = h[yy, xx]
        fav.append(0xFF000000 | (int(p[0]) << 16) | (int(p[1]) << 8) | int(p[2]))
src += emit('fav_hot', 23, 22, fav)
# the marked picture column's header of the bottom sheet (ref/windows-1to1/data_grid_bottom.png, x 26 to 44, y 33 to 51 (the cell is painted one column right of the capture picture)): the Colour marker and the hollow triangle, opaque
b = np.array(Image.open('docs/ui/looks/ref/windows-1to1/data_grid_bottom.png').convert('RGB')).astype(int)
ph = []
for yy in range(33, 52):
    for xx in range(26, 45):
        p = b[yy, xx]
        ph.append(0xFF000000 | (int(p[0]) << 16) | (int(p[1]) << 8) | int(p[2]))
src += emit('pic_head', 19, 19, ph)
# the Sort dialog's sort glyph in the Descending row (ref/windows-1to1/data_grid_sort_states.png, x 512 to 528, y 72 to 87), opaque on the white row
t = np.array(Image.open('docs/ui/looks/ref/windows-1to1/data_grid_sort_states.png').convert('RGB')).astype(int)
sg = []
for yy in range(72, 88):
    for xx in range(512, 529):
        p = t[yy, xx]
        sg.append(0xFF000000 | (int(p[0]) << 16) | (int(p[1]) << 8) | int(p[2]))
src += emit('sort_glyph', 17, 16, sg)
open('lib/e/ui/winedpic.e', 'w', encoding='utf-8').write(src)
