"""Generates lib/e/ui/winmark.e: the check box and radio button marks of the Windows look, baked pixel for
pixel from the live 100 % v3 captures (docs/ui/looks/ref/windows/states), as the button ring is.

  python -I scripts/gen_winmark.py

Each mark is a window of the capture (the control's native box or disc, soft edges included). A pixel
the box shadows against the dialog (an anti-aliased outer pixel: a ray to the window's border meets
only background) is stored as the edge colour with the share it covers, so any background shows
through; every other pixel is stored opaque. A value is 0xAARRGGBB, alpha 0 meaning not painted.
"""
import os

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STATES = os.path.join(ROOT, "docs/ui/looks/ref/windows/states")

# name, capture, x, y, w, h (window in the capture), bg level, edge probe (x offset, y offset in window)
MARKS = [
    ("cb_off_rest", "dialog-options-interface-rest@1x.png", 217, 78, 14, 14),
    ("cb_off_press", "checkbox-pressed-options-hide-splash@1x.png", 217, 78, 14, 14),
    ("cb_on_rest", "dialog-options-grids-rest@1x.png", 226, 106, 14, 14),
    ("cb_on_press", "checkbox-pressed-options-morph-use@1x.png", 217, 75, 14, 14),
    ("rd_off_rest", "dialog-missing-set-cards-rest@1x.png", 24, 398, 13, 14),
    ("rd_off_press", "radio-pressed-missing-set-cards-available@1x.png", 24, 398, 13, 14),
    ("rd_on_rest", "dialog-missing-set-cards-rest@1x.png", 24, 374, 13, 14),
    ("rd_on_press", "radio-pressed-search-cards@1x.png", 28, 134, 13, 14),
    # the Options pages' radio groups are resampled (a different phase): their own marks
    ("rd_opt_off_rest", "dialog-options-grids-rest@1x.png", 232, 268, 14, 14),
    ("rd_opt_off_press", "radio-pressed-options-search-within@1x.png", 232, 268, 14, 14),
    ("rd_opt_on_rest", "dialog-options-grids-rest@1x.png", 232, 226, 14, 14),
    ("rd_opt_on_press", "radio-pressed-options-search-from-start@1x.png", 232, 226, 14, 14),
]
BG = (240, 240, 240)


def outer(px, w, h, x, y):
    """True when a ray from (x, y) to a border of the window meets only background after it."""
    for dx, dy in ((-1, 0), (1, 0), (0, -1), (0, 1)):
        cx, cy = x + dx, y + dy
        clear = True
        while 0 <= cx < w and 0 <= cy < h:
            if px[cx, cy] != BG:
                clear = False
                break
            cx += dx
            cy += dy
        if clear:
            return True
    return False


def bake(capture, x0, y0, w, h):
    im = Image.open(os.path.join(STATES, capture)).convert("RGB").crop((x0, y0, x0 + w, y0 + h))
    px = im.load()
    # the edge colour: the darkest pixel of the middle rows' first dark column
    edge = min((px[x, y] for x in range(w) for y in range(h // 2 - 2, h // 2 + 2)), key=lambda c: sum(c))
    out = []
    for y in range(h):
        for x in range(w):
            v = px[x, y]
            if v == BG:
                out.append(0)
            elif outer(px, w, h, x, y):
                num = sum((BG[i] - v[i]) * (BG[i] - edge[i]) for i in range(3))
                den = sum((BG[i] - edge[i]) ** 2 for i in range(3))
                share = max(0.0, min(1.0, num / den)) if den else 0.0
                a = int(round(share * 255))
                out.append(0 if a == 0 else (a << 24) | (edge[0] << 16) | (edge[1] << 8) | edge[2])
            else:
                out.append(0xFF000000 | (v[0] << 16) | (v[1] << 8) | v[2])
    return out, edge


HEAD = """// The Windows look's check box and radio marks: v3's TcxCheckBox and TcxRadioButton as the native Windows 11
// theme draws them at 96 DPI, painted pixel for pixel from the live captures in docs/ui/looks/ref/windows/states
// (rest and pressed, unchecked and checked or unselected and selected). GENERATED by scripts/gen_winmark.py:
// edit the script, not this file. A value is 0xAARRGGBB, alpha 0 not painted; the edge pixels outside the
// shape carry the edge colour with their coverage so any dialog face shows through. Tables are padded to
// 14 x 14 (a check box mark is 14 across, a radio 13).
// Kinds: 0 check box off rest, 1 off pressed, 2 on rest, 3 on pressed, 4 radio off rest, 5 off pressed,
// 6 on rest, 7 on pressed, 8 to 11 the same four for the Options pages' radio groups.

use e.gfx.geometry
use e.gfx.paint
use e.gfx.scene
use e.mem
use e.ui.layout as ui_layout
use e.ui.style
use e.ui.widget
"""

TAIL = """
fn mark_table(kind: u32) -> [196]u32 {
    if kind == 1u32 { ret mark_cb_off_press() }
    if kind == 2u32 { ret mark_cb_on_rest() }
    if kind == 3u32 { ret mark_cb_on_press() }
    if kind == 4u32 { ret mark_rd_off_rest() }
    if kind == 5u32 { ret mark_rd_off_press() }
    if kind == 6u32 { ret mark_rd_on_rest() }
    if kind == 7u32 { ret mark_rd_on_press() }
    if kind == 8u32 { ret mark_rd_opt_off_rest() }
    if kind == 9u32 { ret mark_rd_opt_off_press() }
    if kind == 10u32 { ret mark_rd_opt_on_rest() }
    if kind == 11u32 { ret mark_rd_opt_on_press() }
    ret mark_cb_off_rest()
}

// The mark's width in px (14 for a check box, 13 for a radio, 14 for the Options pages' radios whose soft edge
// reaches a column further) and its height.
fn mark_width(kind: u32) -> f32 {
    if kind >= 8u32 { ret 14.0 }
    if kind >= 4u32 { ret 13.0 }
    ret 14.0
}

fn mark_height() -> f32 { ret 14.0 }

// `drift`: the vertical sub-pixel shift (px, down) of the capture's resampled theme bitmap at its place in the
// dialog (see control.windows_mark_drift).
type Mark = struct { kind: u32, drift: f32 }

fn mark_measure(ctx: *void, limits: ui_layout.Constraints) -> geometry.Size {
    ret geometry.Size { width: 0.0, height: 0.0 }
}

fn mark_paint(ctx: *void, b: *scene.Builder, area: geometry.Rect) -> err {
    let d = mem.cast[*Mark](ctx)
    let table = mark_table(d.kind)
    let across = usize(mark_width(d.kind))
    // On whole pixels: a mark centred in a cell would otherwise straddle two rows and columns.
    let ox = f32(i32(area.x + 0.5))
    let oy = f32(i32(area.y + 0.5)) + d.drift
    var i = 0usize
    while i < 196usize {
        let v = table[i]
        let alpha = v >> 24u32
        if alpha != 0u32 {
            let c = paint.rgba(f32((v >> 16u32) & 255u32) / 255.0, f32((v >> 8u32) & 255u32) / 255.0, f32(v & 255u32) / 255.0, f32(alpha) / 255.0)
            // An opaque pixel reaches 0.5 under its opaque right and lower neighbours so that a scaled render shows no seams.
            var wide: f32 = 1.0
            var high: f32 = 1.0
            if alpha == 255u32 {
                if i % across + 1usize < across && (table[i + 1usize] >> 24u32) == 255u32 { wide = 1.5 }
                if i + across < 196usize && (table[i + across] >> 24u32) == 255u32 { high = 1.5 }
            }
            try scene.push(b, scene.Command { FillRect: scene.FillRect { rect: geometry.Rect { x: ox + f32(i % across), y: oy + f32(i / across), width: wide, height: high }, brush: paint.Brush { Solid: c } } })
        }
        i += 1usize
    }
    ret ok
}

// The mark of `kind` as a node of its own size.
fn mark_node(a: *mem.Arena, kind: u32, drift: f32) -> (widget.Node, err) {
    let (marks, marks_error) = mem.alloc[Mark](a, 1usize)
    if marks_error != ok { ret (zero, marks_error) }
    marks[0usize] = Mark { kind: kind, drift: drift }
    var s = style.defaults()
    s.width = style.Length { Px: mark_width(kind) }
    s.height = style.Length { Px: mark_height() }
    var none: []const widget.Node = zero
    ret (widget.Node { key: 0u64, kind: widget.Kind { Custom: widget.Custom { ctx: mem.cast[*void](&marks[0usize]), measure: mark_measure, paint: mark_paint, state: widget.bytes_of[Mark](&marks[0usize]) } }, style: s, children: none }, ok)
}
"""


def main():
    lines = []
    for name, capture, x, y, w, h in MARKS:
        table, edge = bake(capture, x, y, w, h)
        # pad the window to 196 values; a check box is 14 across, a radio 13 (the last column is blank)
        table = table + [0] * (196 - len(table))
        body = ", ".join("0x%08Xu32" % v for v in table)
        lines.append("// %s: %s at (%d, %d), %d x %d, edge %s\nfn mark_%s() -> [196]u32 { ret [196]u32{ %s } }" % (
            name, capture, x, y, w, h, edge, name, body))
    out = HEAD + "\n" + "\n".join(lines) + "\n" + TAIL
    with open(os.path.join(ROOT, "lib/e/ui/winmark.e"), "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    print("wrote lib/e/ui/winmark.e")


if __name__ == "__main__":
    main()
