#!/usr/bin/env python3
"""Generates the Encoding Standard tables for e.text.charset from the WHATWG data files.

    python scripts/gen_charset.py indexes.json encodings.json lib/e/text

Fetch https://encoding.spec.whatwg.org/indexes.json and https://encoding.spec.whatwg.org/encodings.json first. Writes
charset_table.e (the single-byte indexes and the label table) and charset_cjk_table.e (Big5, EUC-KR, GB18030, JIS X 0208 and
0212). Each index entry is three bytes (a code point, 0xFFFFFF for none).
"""
import json
import sys

SINGLE = ["ibm866", "iso-8859-2", "iso-8859-3", "iso-8859-4", "iso-8859-5", "iso-8859-6", "iso-8859-7", "iso-8859-8",
          "iso-8859-10", "iso-8859-13", "iso-8859-14", "iso-8859-15", "iso-8859-16", "koi8-r", "koi8-u", "macintosh",
          "windows-874", "windows-1250", "windows-1251", "windows-1252", "windows-1253", "windows-1254", "windows-1255",
          "windows-1256", "windows-1257", "windows-1258", "x-mac-cyrillic"]

def lit(data):
    return '"' + "".join("\\x%02x" % b for b in data) + '"'

def pack3(values, size=None):
    out = bytearray()
    for v in values:
        if v is None:
            v = 0xFFFFFF
        out += bytes([(v >> 16) & 255, (v >> 8) & 255, v & 255])
    return bytes(out)

def main(indexes_path, encodings_path, outdir):
    idx = json.load(open(indexes_path, encoding="utf8"))
    enc = json.load(open(encodings_path, encoding="utf8"))
    head = "// Generated by scripts/gen_charset.py from the WHATWG Encoding Standard data files. Do not edit.\n\n"
    # Core: single-byte indexes and labels.
    out = [head]
    out.append("fn single_count() -> usize { ret %dusize }\n" % len(SINGLE))
    names = []
    for i, name in enumerate(SINGLE):
        table = idx[name]
        assert len(table) == 128, name
        names.append(name)
        out.append("fn single_table_%d() -> str { ret %s }\n" % (i, lit(pack3(table))))
    out.append("fn single_name(i: usize) -> str {")
    for i, name in enumerate(SINGLE):
        out.append("    if i == %dusize { ret \"%s\" }" % (i, name))
    out.append("    ret \"\"\n}\n")
    out.append("fn single_table(i: usize) -> str {")
    for i, name in enumerate(SINGLE):
        out.append("    if i == %dusize { ret single_table_%d() }" % (i, i))
    out.append("    ret \"\"\n}\n")
    # Labels: "label name" pairs separated by newlines.
    pairs = []
    for group in enc:
        for e in group["encodings"]:
            for label in e["labels"]:
                pairs.append((label, e["name"]))
    body = "\\n".join("%s %s" % (l, n) for l, n in pairs)
    out.append("fn label_table() -> str { ret \"%s\\n\" }\n" % body)
    open(outdir + "/charset_table.e", "w", encoding="utf8", newline="\n").write("\n".join(out))
    # CJK indexes.
    out = [head]
    for name, fn in [("big5", "big5"), ("euc-kr", "euc_kr"), ("gb18030", "gb18030"), ("jis0208", "jis0208"), ("jis0212", "jis0212")]:
        table = idx[name]
        out.append("fn index_%s_len() -> usize { ret %dusize }\n" % (fn, len(table)))
        out.append("fn index_%s() -> str { ret %s }\n" % (fn, lit(pack3(table))))
    # gb18030 ranges: pairs (pointer, code point) as 6 bytes.
    ranges = idx["gb18030-ranges"]
    rb = bytearray()
    for p, cp in ranges:
        rb += bytes([(p >> 16) & 255, (p >> 8) & 255, p & 255, (cp >> 16) & 255, (cp >> 8) & 255, cp & 255])
    out.append("fn gb18030_ranges_len() -> usize { ret %dusize }\n" % len(ranges))
    out.append("fn gb18030_ranges() -> str { ret %s }\n" % lit(bytes(rb)))
    open(outdir + "/charset_cjk_table.e", "w", encoding="utf8", newline="\n").write("\n".join(out))

main(*sys.argv[1:4])
