"""Print the generated tables of lib/e/net/http2.e (HPACK static table and Huffman code), from the `hpack` package.

    PYTHONPATH=DIR python scripts/http2_tables.py > tables.e.txt

The output is two Neper functions: `static_name`/`static_value` over the 61 static entries, and `huffman_table`, 257
five-byte records (code big-endian in four bytes, then its length in bits) in symbol order, EOS last. The generator
asserts the code is canonical (codes assigned by increasing length then symbol), which the decoder relies on.
"""
from hpack import huffman_constants as c
from hpack.table import HeaderTable

BS = chr(92)


def lit(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out.append(BS + '"')
        elif ch == BS:
            out.append(BS + BS)
        elif 32 <= o < 127:
            out.append(ch)
        else:
            out.append(BS + 'x%02X' % o)
    return '"' + ''.join(out) + '"'


def main():
    syms = sorted(range(257), key=lambda s: (c.REQUEST_CODES_LENGTH[s], s))
    code, prev = 0, c.REQUEST_CODES_LENGTH[syms[0]]
    for i, s in enumerate(syms):
        length = c.REQUEST_CODES_LENGTH[s]
        code = 0 if i == 0 else (code + 1) << (length - prev)
        prev = length
        assert code == c.REQUEST_CODES[s], s
    raw = b''.join(c.REQUEST_CODES[s].to_bytes(4, 'big') + bytes([c.REQUEST_CODES_LENGTH[s]]) for s in range(257))
    static = HeaderTable.STATIC_TABLE
    assert len(static) == 61
    print('// Generated by scripts/http2_tables.py from the `hpack` package (RFC 7541 appendices A and B); do not edit.')
    print('fn static_name(index: usize) -> str {')
    for i, (n, v) in enumerate(static):
        print('    if index == %dusize { ret %s }' % (i + 1, lit(n.decode('ascii'))))
    print('    ret ""\n}\n')
    print('fn static_value(index: usize) -> str {')
    for i, (n, v) in enumerate(static):
        if v:
            print('    if index == %dusize { ret %s }' % (i + 1, lit(v.decode('ascii'))))
    print('    ret ""\n}\n')
    print('// 257 records of five bytes: the code (big-endian u32) and its length in bits; symbol 256 is EOS.')
    print('fn huffman_table() -> str {\n    ret %s\n}' % lit(raw.decode('latin-1')))


main()
