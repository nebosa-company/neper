"""Bakes v3's popup menu pictures (16 x 16, one per pictured item) into lib/e/ui/winmenuicon.e.
Cut from the menu captures docs/ui/looks/ref/windows/popup_menu_*.png at the item rows of the menu specs in
examples/looks/popup_menu.e (item tops: 3, +10 before a separated item, a header 22 tall (24 when not the first), other items 20;
the picture is 16 x 16 at x 5, 2 below the item top). Items highlighted or under the pointer are skipped, so the picture is read
off a row on the plain face (#F0F0F0, which is not painted). A picture is keyed by its label, whether the item is disabled and whether it sits in a frame (a checked item's sunken one, the highlighted
item's raised one: there face and white count as the ground, alpha 0, since the code paints the frame and its dither under the tile).
Table and Sigma (flags t, m) are drawn by navigation.windows_menu_pixmap and not baked. Edit this script, not the generated file."""
import re, sys
from PIL import Image
L = 'docs/ui/looks/ref/windows/'
src = open('examples/looks/popup_menu.e').read()
menus = []
for m in re.finditer(r'Spec \{ name: "([^"]+)", limit: ([0-9.]+), w: [0-9.]+, h: [0-9.]+, items: "([^"]*)"', src):
    menus.append((m.group(1), m.group(3), float(m.group(2))))
sd = re.search(r'fn state_data\(\) -> str \{ ret "(.*)" \}', src, re.S).group(1)
for line in sd.split('#'):
    f = line.split('@')
    if len(f) >= 5:
        menus.append((f[0], f[4], float(f[3])))
tiles = {}   # (label, disabled) -> (pixels, source)
clash = []
for name, items, limit in menus:
    try:
        im = Image.open(L + name + '.png').convert('RGB')
    except FileNotFoundError:
        continue
    y = 3
    first = True
    for it in items.split('|'):
        flags, label, *_ = (it.split(';') + ['', ''])
        if 's' in flags and not first:
            y += 10
        if 'h' in flags:
            h = 22 if first else 24
        else:
            h = 20
        top = y
        y += h
        first = False
        if 'p' not in flags or 't' in flags or 'm' in flags:
            continue
        framed = 'c' in flags or 'x' in flags
        if top + 18 > im.height or (limit > 0 and top + 18 > limit - 26):  # a limited menu ends in the scroll arrow
            continue
        # the capture's pointer-hot rows are blue at the right of the picture: skip a row whose face is not #F0F0F0
        if not framed and im.getpixel((24, top + 1)) != (240, 240, 240):
            continue
        px = []
        for yy in range(16):
            for xx in range(16):
                p = im.getpixel((5 + xx, top + 2 + yy))
                px.append(0 if p == (240, 240, 240) or (framed and p == (255, 255, 255)) else 0xFF000000 | p[0] << 16 | p[1] << 8 | p[2])
        key = (label, 'd' in flags, framed)
        if key in tiles:
            if tiles[key][0] != px:
                clash.append((key, name, tiles[key][1]))
        else:
            tiles[key] = (px, name)
for c in clash:
    print('CLASH', c, file=sys.stderr)
keys = sorted(tiles)
print(len(keys), 'pictures', len(clash), 'clashes', file=sys.stderr)
out = ['// GENERATED by scripts/gen_winmenuicon.py from the menu captures in ref/windows: v3\'s popup menu pictures, %d tiles of 16 x 16,' % len(keys),
       '// 0xAARRGGBB, alpha 0 = the menu face. Edit the script, not this file.', '', 'use e.str as strs', '',
       'fn count() -> usize { ret %dusize }' % len(keys), '',
       '// The tile of the pictured item `label` (disabled or not, framed or not), 1000 when v3 has none baked.',
       'fn find(label: str, disabled: bool, framed: bool) -> usize {']
for dis in (False, True):
    for fr in (False, True):
        out.append('    if %s && %s {' % ('disabled' if dis else '!disabled', 'framed' if fr else '!framed'))
        for i, k in enumerate(keys):
            if k[1] == dis and k[2] == fr:
                out.append('        if strs.eq(label, "%s") { ret %dusize }' % (k[0].replace('"', '\\"'), i))
        out.append('    }')
out.append('    ret 1000usize\n}\n')
vals = [v for k in keys for v in tiles[k][0]]
out.append('fn atlas() -> [%d]u32 { ret [%d]u32{ %s } }' % (len(vals), len(vals), ', '.join('0x%08Xu32' % v for v in vals)))
open('lib/e/ui/winmenuicon.e', 'w', newline='\n').write('\n'.join(out) + '\n')
