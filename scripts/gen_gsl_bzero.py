o.append('''fn eps() -> f64 { ret 2.2204460492503131e-16f64 }
fn fa(x: f64) -> f64 { ret math.abs[f64](x) }
fn mpi() -> f64 { ret 3.141592653589793238462643383279f64 }

fn clenshaw(kind: usize, s: usize, n: usize, u: f64) -> f64 {
    let big = n
    var bnp1 = 0.0f64
    var bn = 0.0f64
    if kind == 0usize { bn = jz_ca(s, big) } else { bn = jz_cb(s, big) }
    var i = big
    while i > 0usize {
        var c = 0.0f64
        if kind == 0usize { c = jz_ca(s, i - 1usize) } else { c = jz_cb(s, i - 1usize) }
        let bnm1 = 2.0f64 * (2.0f64 * u - 1.0f64) * bn - bnp1 + c
        bnp1 = bn
        bn = bnm1
        i -= 1usize
    }
    ret bn - (2.0f64 * u - 1.0f64) * bnp1
}

fn mcmahon_correction(mu: f64, beta: f64) -> f64 {
    let eb = 8.0f64 * beta
    let ebsq = eb * eb
    if mu < eps() {
        let term1 = 1.0f64 / ebsq
        let term2 = -4.0f64 * 31.0f64 / (3.0f64 * ebsq * ebsq)
        let term3 = 32.0f64 * 3779.0f64 / (15.0f64 * ebsq * ebsq * ebsq)
        let term4 = -64.0f64 * 6277237.0f64 / (105.0f64 * ebsq * ebsq * ebsq * ebsq)
        let term5 = 512.0f64 * 2092163573.0f64 / (315.0f64 * ebsq * ebsq * ebsq * ebsq * ebsq)
        ret 1.0f64 + 8.0f64 * (term1 + term2 + term3 + term4 + term5)
    }
    let mi = 1.0f64 / mu
    let r = mu / ebsq
    let n2 = 4.0f64 / 3.0f64 * (7.0f64 - 31.0f64 * mi)
    let n3 = 32.0f64 / 15.0f64 * (83.0f64 + (-982.0f64 + 3779.0f64 * mi) * mi)
    let n4 = 64.0f64 / 105.0f64 * (6949.0f64 + (-153855.0f64 + (1585743.0f64 - 6277237.0f64 * mi) * mi) * mi)
    let n5 = 512.0f64 / 315.0f64 * (70197.0f64 + (-2479316.0f64 + (48010494.0f64 + (-512062548.0f64 + 2092163573.0f64 * mi) * mi) * mi) * mi)
    let n6 = 2048.0f64 / 3465.0f64 * (5592657.0f64 + (-287149133.0f64 + (8903961290.0f64 + (-179289628602.0f64 + (1982611456181.0f64 - 8249725736393.0f64 * mi) * mi) * mi) * mi) * mi)
    let term1 = (1.0f64 - mi) * r
    let term2 = term1 * n2 * r
    let term3 = term1 * n3 * r * r
    let term4 = term1 * n4 * r * r * r
    let term5 = term1 * n5 * r * r * r * r
    let term6 = term1 * n6 * r * r * r * r * r
    ret 1.0f64 - 8.0f64 * (term1 + term2 + term3 + term4 + term5 + term6)
}

fn pow14(x0: f64) -> f64 {
    var x = x0
    var v = 1.0f64
    var count = 14usize
    while count > 0usize {
        if count % 2usize == 1usize { v *= x }
        count /= 2usize
        x *= x
    }
    ret v
}

// gsl_sf_bessel_zero_J0_e; s = 0 is a domain error (0, 0)
fn bessel_zero_j0(s: usize) -> (f64, f64) {
    if s == 0usize { ret (0.0f64, 0.0f64) }
    let p0 = 1567450796.0f64 / 12539606369.0f64
    let p1 = 8903660.0f64 / 2365861.0f64
    let p2 = 10747040.0f64 / 536751.0f64
    let p3 = 17590991.0f64 / 1696654.0f64
    let q1 = 29354255.0f64 / 954518.0f64
    let q2 = 76900001.0f64 / 431847.0f64
    let q3 = 67237052.0f64 / 442411.0f64
    let beta = (f64(s) - 0.25f64) * mpi()
    let bi2 = 1.0f64 / (beta * beta)
    let num = p0 + bi2 * (p1 + bi2 * (p2 + p3 * bi2))
    let den = 1.0f64 + bi2 * (q1 + bi2 * (q2 + q3 * bi2))
    let v = beta + num / den / beta
    ret (v, fa(3.0e-15f64 * v))
}

// gsl_sf_bessel_zero_J1_e
fn bessel_zero_j1(s: usize) -> (f64, f64) {
    if s == 0usize { ret (0.0f64, 0.0f64) }
    let a0 = -0.362804405737084f64
    let a1 = 0.120341279038597f64
    let a2 = 0.439454547101171e-01f64
    let a3 = 0.159340088474713e-02f64
    let b0 = 1.0f64
    let b1 = -0.325641790801361f64
    let b2 = -0.117453445968927f64
    let b3 = -0.424906902601794e-02f64
    let beta = (f64(s) + 0.25f64) * mpi()
    let bi2 = 1.0f64 / (beta * beta)
    let rnum = a3 + bi2 * (a2 + bi2 * (a1 + bi2 * a0))
    let rden = b3 + bi2 * (b2 + bi2 * (b1 + bi2 * b0))
    let r = rnum / rden
    let v = beta * (1.0f64 + r * bi2)
    ret (v, fa(2.0e-14f64 * v))
}

// true when gsl_sf_bessel_zero_Jnu_e takes its Olver uniform asymptotic branch (nu >= 0, s > 20 or s <= nu / 2, and s <= 2 nu)
fn jnu_olver_branch(nu: f64, s: usize) -> bool {
    if s == 0usize || nu < 0.0f64 { ret false }
    if s == 1usize || s <= 10usize { ret false }
    let sf = f64(s)
    if sf > 0.5f64 * nu && s <= 20usize { ret false }
    if sf > 2.0f64 * nu { ret false }
    ret true
}

// gsl_sf_bessel_zero_Jnu_e outside the Olver branch; nu <= -1 is a domain error and -1 < nu < 0 unimplemented, both (0, 0)
fn bessel_zero_jnu(nu: f64, s: usize) -> (f64, f64) {
    if nu <= -1.0f64 || s == 0usize || nu < 0.0f64 { ret (0.0f64, 0.0f64) }
    let sf = f64(s)
    if s == 1usize {
        if nu < 2.0f64 {
            let chb = clenshaw(0usize, s, jz_na(s) - 1usize, nu / 2.0f64)
            ret (chb, 2.0e-15f64 * chb)
        }
        let arg = math.pow[f64](2.0f64 / nu, 2.0f64 / 3.0f64)
        let chb = clenshaw(1usize, s, jz_nb(s) - 1usize, arg)
        let v = nu * chb
        ret (v, 2.0e-15f64 * v)
    }
    if s <= 10usize {
        if nu < sf {
            let chb = clenshaw(0usize, s, jz_na(s) - 1usize, nu / sf)
            ret (chb, 2.0e-15f64 * chb)
        }
        let arg = math.pow[f64](sf / nu, 2.0f64 / 3.0f64)
        let chb = clenshaw(1usize, s, jz_nb(s) - 1usize, arg)
        let v = nu * chb
        var e = 2.0e-15f64 * v
        if s == 5usize { e *= 5.0e+06f64 }
        ret (v, e)
    }
    if sf > 0.5f64 * nu && s <= 20usize {
        let chb = clenshaw(0usize, s, jz_na(s) - 1usize, nu / (2.0f64 * sf))
        ret (chb, 4.0e-15f64 * chb)
    }
    let beta = (sf + 0.5f64 * nu - 0.25f64) * mpi()
    let mc = mcmahon_correction(4.0f64 * nu * nu, beta)
    let v = beta * mc
    ret (v, 4.0f64 * fa(beta) * pow14(nu / beta) + 4.0f64 * fa(eps() * v))
}

fn zero_f(z: f64) -> f64 {
    let pre = math.pow[f64](z, 2.0f64 / 3.0f64)
    let zi2 = 1.0f64 / (z * z)
    let zi4 = zi2 * zi2
    let t1 = 5.0f64 / 48.0f64 * zi2
    let t2 = -5.0f64 / 36.0f64 * zi4
    let t3 = 77125.0f64 / 82944.0f64 * zi4 * zi2
    let t4 = -108056875.0f64 / 6967296.0f64 * zi4 * zi4
    ret pre * (1.0f64 + t1 + t2 + t3 + t4)
}

fn zero_g(z: f64) -> f64 {
    let pre = math.pow[f64](z, 2.0f64 / 3.0f64)
    let zi2 = 1.0f64 / (z * z)
    let zi4 = zi2 * zi2
    let t1 = -7.0f64 / 48.0f64 * zi2
    let t2 = 35.0f64 / 288.0f64 * zi4
    let t3 = -181223.0f64 / 207360.0f64 * zi4 * zi2
    let t4 = 18683371.0f64 / 1244160.0f64 * zi4 * zi4
    ret pre * (1.0f64 + t1 + t2 + t3 + t4)
}

// airy_zero kind 0 Ai, 1 Bi, 2 Ai', 3 Bi' (gsl_sf_airy_zero_*_e)
fn airy_zero(kind: usize, s: usize) -> (f64, f64) {
    if s < 1usize { ret (0.0f64, 0.0f64) }
    var tab = 0.0f64
    var n = 0usize
    if kind == 0usize {
        n = az_n_zero_Ai()
        tab = az_zero_Ai(s)
    }
    if kind == 1usize {
        n = az_n_zero_Bi()
        tab = az_zero_Bi(s)
    }
    if kind == 2usize {
        n = az_n_zero_Aip()
        tab = az_zero_Aip(s)
    }
    if kind == 3usize {
        n = az_n_zero_Bip()
        tab = az_zero_Bip(s)
    }
    if s < n { ret (tab, eps() * fa(tab)) }
    let sf = f64(s)
    var z = 0.0f64
    if kind == 0usize { z = 3.0f64 * mpi() / 8.0f64 * (4.0f64 * sf - 1.0f64) }
    if kind == 1usize { z = 3.0f64 * mpi() / 8.0f64 * (4.0f64 * sf - 3.0f64) }
    if kind == 2usize { z = 3.0f64 * mpi() / 8.0f64 * (4.0f64 * sf - 3.0f64) }
    if kind == 3usize { z = 3.0f64 * mpi() / 8.0f64 * (4.0f64 * sf - 1.0f64) }
    var f = 0.0f64
    if kind <= 1usize { f = zero_f(z) } else { f = zero_g(z) }
    ret (0.0f64 - f, 2.0f64 * eps() * f)
}''')
