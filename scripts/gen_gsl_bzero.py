o.append('// gsl 2.7.1 bessel_zero_J0, J1, Jnu and airy_zero_Ai, Bi, Ai_deriv, Bi_deriv with gsl\'s error estimates (specfunc/bessel_zero.c, airy_zero.c); the Chebyshev and zero tables are generated by scripts/gen_gsl_bzero.py.')
o.append('// Every function returns (value, error). jnu_olver_branch(nu, s) says whether Jnu takes the Olver branch, which this module does not port.')
