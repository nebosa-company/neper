def lit(v):
    v = v.strip()
    if re.fullmatch(r'[-+]?\d+', v):
        v += '.0'
    v = re.sub(r'^([-+]?)\.', r'\g<1>0.', v)
    v = v.lstrip('+')
    return v + 'f64'


def strip(s):
    return re.sub(r'/\*.*?\*/', '', s, flags=re.S)


bz = strip(open(SRC + 'bessel_zero.c', encoding='utf8').read())
az = strip(open(SRC + 'airy_zero.c', encoding='utf8').read())


def arr(src, name):
    m = re.search(r'static const double ' + name + r'\[\]\s*=\s*\{(.*?)\};', src, flags=re.S)
    return [x for x in re.split(r'[,\s]+', m.group(1)) if x]


