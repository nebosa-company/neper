"""Bakes v3's page control tab pictures (the Statistics window's eleven 16 x 16 bitmaps) into lib/e/ui/winpageicon.e.
Cut from docs/ui/looks/ref/windows/page_control_stats.png (Colors chosen) at the boxes where the strip puts the pictures;
a white pixel is the tab face and is not painted. Keyed by the tab's caption without its mnemonic. Edit this script, not the generated file."""
from PIL import Image
import numpy as np
# The pictures stand 2 px higher on a tab that is not chosen (y 36) than on the chosen one (y 38), so each is cut from a sheet where its tab is
# not chosen (Colors from the capture whose chosen tab is Editions) at the column where its body starts.
L = 'docs/ui/looks/ref/windows/'
TABS = [("Colors", 21, 'page_control_stats_4'), ("Rarity", 82, 'page_control_stats'), ("Card Type", 141, 'page_control_stats'), ("Editions", 221, 'page_control_stats'),
        ("Mana Analyser", 288, 'page_control_stats'), ("Mana Product", 389, 'page_control_stats'), ("Power Analyser", 485, 'page_control_stats'),
        ("Probability", 590, 'page_control_stats'), ("Mana Slots", 670, 'page_control_stats'), ("Start Hand", 752, 'page_control_stats'), ("Advanced", 834, 'page_control_stats')]
vals = []
for _, x0, sheet in TABS:
    im = Image.open(L + sheet + '.png').convert('RGB')
    a = np.array(im).astype(int)
    left = min(x for x in range(x0 - 3, x0 + 4) if (np.abs(a[36:53, x] - 255).max(axis=1) > 2).any())
    # the last two bitmaps have a blank first column, so the scan finds the second
    if x0 in (752, 834):
        left -= 1
    for y in range(16):
        for x in range(16):
            p = im.getpixel((left + x, 36 + y))
            vals.append(0 if p == (255, 255, 255) else 0xFF000000 | p[0] << 16 | p[1] << 8 | p[2])
out = ['// GENERATED by scripts/gen_winpageicon.py from ref/windows/page_control_stats.png: v3\'s Statistics tab pictures, %d tiles of 16 x 16,' % len(TABS),
       '// 0xAARRGGBB, alpha 0 = the tab face. Edit the script, not this file.', '', 'use e.str as strs', '',
       '// The tile of the tab captioned `label` (no mnemonic), 1000 when v3 has none baked.', 'fn find(label: str) -> usize {']
for i, (name, _, _s) in enumerate(TABS):
    out.append('    if strs.eq(label, "%s") { ret %dusize }' % (name, i))
out.append('    ret 1000usize\n}\n')
out.append('fn atlas() -> [%d]u32 { ret [%d]u32{ %s } }' % (len(vals), len(vals), ', '.join('0x%08Xu32' % v for v in vals)))
open('lib/e/ui/winpageicon.e', 'w', newline='\n').write('\n'.join(out) + '\n')
